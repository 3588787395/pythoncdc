#!/usr/bin/env python3
"""R36 probe: dump region classification for Trade.create_trade."""
import sys, marshal, types
sys.path.insert(0, r'F:/Downloads/pythoncdc-main')

from core.cfg.cfg_builder import build_cfg
from core.cfg.region_analyzer import RegionAnalyzer

with open(r'F:/Downloads/pythoncdc-main/site-packages/IQEngine/account/trade.pyc', 'rb') as f:
    f.read(16)
    code = marshal.load(f)


def find(code, name):
    for c in code.co_consts:
        if hasattr(c, 'co_name'):
            if c.co_name == name:
                return c
            r = find(c, name)
            if r:
                return r
    return None


ct = find(code, 'create_trade')
cfg = build_cfg(ct)
analyzer = RegionAnalyzer(cfg)
regions = analyzer.analyze()
print(f"total regions: {len(regions)}")
for r in regions:
    e = getattr(r.entry, 'start_offset', None)
    blocks = sorted(getattr(b, 'start_offset', -1) for b in getattr(r, 'blocks', []))
    mc = getattr(r, 'merge_context', None)
    vt = getattr(r, 'value_target', None)
    mb = getattr(r, 'merge_block', None)
    mbo = getattr(mb, 'start_offset', None) if mb is not None else None
    print(f"{type(r).__name__:24s} entry@{e} merge@{mbo} mc={mc} vt={vt} parent={type(getattr(r,'parent',None)).__name__}")
    print(f"    blocks={blocks}")
for b in cfg.blocks:
    instrs = [(i.offset, i.opname) for i in b.instructions]
    print(f"block@{b.start_offset}: {instrs[:6]}{'...' if len(instrs) > 6 else ''} succ={[s.start_offset for s in b.successors]}")
