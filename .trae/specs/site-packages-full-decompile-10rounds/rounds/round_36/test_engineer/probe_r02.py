#!/usr/bin/env python3
"""R36 probe: dump regions for a repro source."""
import sys
sys.path.insert(0, r'F:/Downloads/pythoncdc-main')

from core.cfg.cfg_builder import build_cfg
from core.cfg.region_analyzer import RegionAnalyzer

src = open(sys.argv[1], encoding='utf-8').read()
code = compile(src, '<repro>', 'exec')
fn = None
for c in code.co_consts:
    if hasattr(c, 'co_name'):
        fn = c
        break
cfg = build_cfg(fn)
for b in cfg.get_blocks_in_order():
    last = b.instructions[-1]
    print(f"block@{b.start_offset}..{last.offset} last={last.opname} succs={[s.start_offset for s in b.conditional_successors]}")
analyzer = RegionAnalyzer(cfg)
regions = analyzer.analyze()
print(f"--- regions: {len(regions)} ---")
for r in regions:
    e = getattr(r.entry, 'start_offset', None)
    blocks = sorted(getattr(b, 'start_offset', -1) for b in getattr(r, 'blocks', []))
    mc = getattr(r, 'merge_context', None)
    vt = getattr(r, 'value_target', None)
    print(f"{type(r).__name__:22s} entry@{e} mc={mc} vt={vt} parent={type(getattr(r,'parent',None)).__name__} blocks={blocks}")
