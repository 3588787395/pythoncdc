def create(cls, price, amount, order_id, commission, tax, trade_id):
    obj = cls()
    env_dt = price or amount
    obj._price = price
    obj._amount = amount
    obj._order_id = order_id
    obj._commission = commission
    obj._tax = tax
    obj._trade_id = trade_id if trade_id is not None else obj._make_id()
    obj._status = tax
    return obj
