#!/usr/bin/env python3
"""R36 probe2: trace _detect_ternary_pattern return lines for create_trade."""
import sys, marshal
sys.path.insert(0, r'F:/Downloads/pythoncdc-main')

from core.cfg.cfg_builder import build_cfg
from core.cfg.region_analyzer import RegionAnalyzer

with open(r'F:/Downloads/pythoncdc-main/site-packages/IQEngine/account/trade.pyc', 'rb') as f:
    f.read(16)
    code = marshal.load(f)


def find(code, name):
    for c in code.co_consts:
        if hasattr(c, 'co_name'):
            if c.co_name == name:
                return c
            r = find(c, name)
            if r:
                return r
    return None


ct = find(code, 'create_trade')
cfg = build_cfg(ct)

TARGET_LINES = set()
traces = []


def tracer(frame, event, arg):
    if event == 'call' and frame.f_code.co_name == '_detect_ternary_pattern':
        blk = frame.f_locals.get('block')
        off = getattr(blk, 'start_offset', None)
        if off == 104:
            return local_tracer
    return None


def local_tracer(frame, event, arg):
    if event == 'return':
        traces.append((frame.f_lineno, arg is None))
    return local_tracer


analyzer = RegionAnalyzer(cfg)
sys.settrace(tracer)
try:
    analyzer.analyze()
finally:
    sys.settrace(None)
print("block@186 _detect_ternary_pattern returns:", traces)
