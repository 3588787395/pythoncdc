"""Round 13 最小复现集运行器。

针对家族 W13（try/finally 尾部 return 语句返回值丢失）的 12 个最小复现：
对 minimal_repros/ 下每个 repro：
  1. compile(src) 得到原始 code object；
  2. core.cfg.decompile(src) 得到反编译文本；
  3. compile(反编译文本) 得到新 code object（剥离 # 头部行）；
  4. compare_bytecode.compare_all 逐函数比较 co_code / co_consts / co_exceptiontable。
打印每个 repro 的 PASS/FAIL（FAIL 时给出首个差异），写 repro_results.txt + SUMMARY.txt。
预期（缺陷未修）：12/12 文件 FAIL；修复后必须全 PASS。
"""
import os
