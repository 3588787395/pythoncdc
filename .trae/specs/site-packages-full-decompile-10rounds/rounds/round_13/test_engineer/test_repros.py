from core.cfg import decompile as decompile_src
import compare_bytecode as cb


def run_repro(py_path):
    """compile → decompile → re-compile → 逐函数比较。返回 (ok, 明细)。"""
    with open(py_path, 'r', encoding='utf-8') as f:
        src = f.read()

    try:
        orig_code = compile(src, py_path, 'exec')
    except SyntaxError as e:
        return False, f"原始源码编译失败: {e}"

    try:
        text = decompile_src(src)
    except Exception as e:
        return False, f"反编译异常: {type(e).__name__}: {e}"

    if not isinstance(text, str):
        return False, f"反编译返回非字符串: {type(text)!r}"

    try:
        decomp_code = cb.compile_decompiled_source(text)
    except SyntaxError as e:
        return False, f"反编译文本重编译失败: {e}"

    results, passed, total = cb.compare_all(orig_code, decomp_code)
    details = [f"{name}: {'PASS' if ok else 'FAIL - ' + detail}"
               for name, ok, detail in results]
    return passed == total, '; '.join(details)


def main():
    base = os.path.dirname(os.path.abspath(__file__))
    repro_dir = os.path.join(base, 'minimal_repros')
    files = sorted(fn for fn in os.listdir(repro_dir)
                   if fn.endswith('.py') and not fn.startswith('__'))
    buf = [f"=== Round 13 repro 集运行: {len(files)} 个用例（家族 W13: finally-return 返回值丢失） ==="]
    passed_n = 0
    failed_n = 0
    func_pass = 0
    func_total = 0
    for fn in files:
        py_path = os.path.join(repro_dir, fn)
        try:
            ok, detail = run_repro(py_path)
        except Exception as e:
            ok, detail = False, f"运行器异常: {type(e).__name__}: {e}"
        if not ok and detail.startswith('反编译异常') is False:
            pass
        # 统计函数级通过数（detail 为逐函数拼接，此处按文件级汇总即可）
        if ok:
            passed_n += 1
            buf.append(f"[PASS] {fn}")
        else:
            failed_n += 1
            buf.append(f"[FAIL] {fn}")
            for line in detail.split('; '):
                buf.append(f"       {line}")
    total = passed_n + failed_n
    rate = passed_n / total if total else 0.0
    buf.append("")
    buf.append("=== SUMMARY ===")
    buf.append(f"files: {passed_n}/{total} PASS ({rate:.3f}), {failed_n} FAIL")
    buf.append("预期: 缺陷未修复时 0/12 PASS；修复验收标准为 12/12 全 PASS。")
    report = '\n'.join(buf) + '\n'
    print(report)

    out_path = os.path.join(base, 'repro_results.txt')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(report)

    sum_path = os.path.join(base, 'SUMMARY.txt')
    with open(sum_path, 'w', encoding='utf-8') as f:
        f.write(f"Round 13 repro SUMMARY: files {passed_n}/{total} PASS, "
                f"{failed_n} FAIL (基线=缺陷复现: 预期全 FAIL; 验收=12/12 PASS)\n")
    return failed_n


if __name__ == '__main__':
    sys.exit(0 if main() == 0 else 1)
