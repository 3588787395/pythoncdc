"""Test all Round 02 minimal reproduction cases - compile, decompile, compare bytecode."""
import os, sys, dis, marshal, types

sys.path.insert(0, 'f:/Downloads/pythoncdc-main')
os.chdir('f:/Downloads/pythoncdc-main')
from pycdc import decompile_pyc

def load_code_from_pyc(pyc_path):
    with open(pyc_path, 'rb') as f:
        f.read(16)
        code = marshal.load(f)
    return code

def compare_code_objects(orig_code, decomp_code):
    if orig_code.co_code != decomp_code.co_code:
        return False, "code mismatch"
    if orig_code.co_exceptiontable != decomp_code.co_exceptiontable:
        return False, "exception table mismatch"
    orig_funcs = [c for c in orig_code.co_consts if hasattr(c, 'co_code')]
    decomp_funcs = [c for c in decomp_code.co_consts if hasattr(c, 'co_code')]
    if len(orig_funcs) != len(decomp_funcs):
        return False, f"func count {len(orig_funcs)} vs {len(decomp_funcs)}"
    for of, df in zip(orig_funcs, decomp_funcs):
        ok, msg = compare_code_objects(of, df)
        if not ok:
            return False, f"{of.co_name}: {msg}"
    return True, "match"

repro_dir = '.trae/specs/site-packages-full-decompile-10rounds/rounds/round_02/test_engineer/minimal_repros'
results = []

for filename in sorted(os.listdir(repro_dir)):
    if not filename.endswith('.py'):
        continue
    
    py_path = os.path.join(repro_dir, filename)
    
    with open(py_path, 'r', encoding='utf-8') as f:
        source = f.read()
    
    try:
        code = compile(source, py_path, 'exec')
    except SyntaxError as e:
        print(f"[FAIL] {filename}: compile error: {e}")
        results.append((filename, False, str(e)))
        continue
    
    pyc_path = py_path.replace('.py', '.pyc')
    with open(pyc_path, 'wb') as f:
        f.write(b'\x6f\x0d\x0d\x0a')
        f.write(b'\x00\x00\x00\x00')
        f.write(b'\x00\x00\x00\x00')
        f.write(b'\x00\x00\x00\x00')
        marshal.dump(code, f)
    
    try:
        decomp_source = decompile_pyc(pyc_path)
    except Exception as e:
        print(f"[FAIL] {filename}: decompile error: {e}")
        results.append((filename, False, str(e)))
        continue
    
    lines = decomp_source.split('\n')
    while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
        lines.pop(0)
    decomp_source = '\n'.join(lines)
    
    try:
        decomp_code = compile(decomp_source, '<decompiled>', 'exec')
    except SyntaxError as e:
        print(f"[FAIL] {filename}: decompiled compile error: {e}")
        results.append((filename, False, str(e)))
        continue
    
    orig_code = load_code_from_pyc(pyc_path)
    ok, msg = compare_code_objects(orig_code, decomp_code)
    
    if ok:
        print(f"[PASS] {filename}")
        results.append((filename, True, ""))
    else:
        print(f"[FAIL] {filename}: {msg}")
        results.append((filename, False, msg))
        
        orig_funcs = {c.co_name: c for c in orig_code.co_consts if hasattr(c, 'co_code')}
        decomp_funcs = {c.co_name: c for c in decomp_code.co_consts if hasattr(c, 'co_code')}
        for name, of in orig_funcs.items():
            if name in decomp_funcs:
                df = decomp_funcs[name]
                if of.co_code != df.co_code:
                    orig_instrs = list(dis.get_instructions(of))
                    decomp_instrs = list(dis.get_instructions(df))
                    for i in range(max(len(orig_instrs), len(decomp_instrs))):
                        o = orig_instrs[i] if i < len(orig_instrs) else None
                        d = decomp_instrs[i] if i < len(decomp_instrs) else None
                        if o is None:
                            print(f"  Extra: {d.opname} {d.argrepr}")
                            break
                        if d is None:
                            print(f"  Missing: {o.opname} {o.argrepr}")
                            break
                        if o.opname != d.opname or o.arg != d.arg:
                            print(f"  [{i}] ORIG: {o.opname} {o.argrepr}")
                            print(f"  [{i}] DECP: {d.opname} {d.argrepr}")
                            break

passed = sum(1 for _, ok, _ in results if ok)
failed = sum(1 for _, ok, _ in results if not ok)
print(f"\n=== SUMMARY: {passed} passed, {failed} failed ===")
