from pycdc import decompile_pyc

def load_code_from_pyc(pyc_path):
    with open(pyc_path, 'rb') as f:
        f.read(16)
        return marshal.load(f)

def find_mismatches(orig_code, decomp_code, prefix="", depth=0):
    """Find all bytecode mismatches recursively."""
    mismatches = []
    if orig_code.co_code != decomp_code.co_code:
        orig_instrs = list(dis.get_instructions(orig_code))
        decomp_instrs = list(dis.get_instructions(decomp_code))
        diffs = []
        for i in range(max(len(orig_instrs), len(decomp_instrs))):
            o = orig_instrs[i] if i < len(orig_instrs) else None
            d = decomp_instrs[i] if i < len(decomp_instrs) else None
            if o is None:
                diffs.append((i, None, d))
                break
            if d is None:
                diffs.append((i, o, None))
                break
            if o.opname != d.opname or o.arg != d.arg:
                diffs.append((i, o, d))
                if len(diffs) >= 3:
                    break
        mismatches.append({
            'func': prefix or '<module>',
            'orig_len': len(orig_instrs),
            'decomp_len': len(decomp_instrs),
            'diffs': diffs
        })
    
    orig_funcs = [c for c in orig_code.co_consts if hasattr(c, 'co_code')]
    decomp_funcs = [c for c in decomp_code.co_consts if hasattr(c, 'co_code')]
    if len(orig_funcs) != len(decomp_funcs):
        mismatches.append({
            'func': f"{prefix} - func count mismatch",
            'orig_len': len(orig_funcs),
            'decomp_len': len(decomp_funcs),
            'diffs': []
        })
    else:
        for of, df in zip(orig_funcs, decomp_funcs):
            mismatches.extend(find_mismatches(of, df, f"{prefix}{of.co_name}" if prefix else of.co_name, depth+1))
    return mismatches

# Select a few failing files to analyze
