import sys, os, marshal, dis

sys.path.insert(0, 'f:/Downloads/pythoncdc-main')
os.chdir('f:/Downloads/pythoncdc-main')
from pycdc import decompile_pyc

def load_code_from_pyc(pyc_path):
    with open(pyc_path, 'rb') as f:
        f.read(16)
        return marshal.load(f)

# Analyze const.pyc format_engine
print("="*60)
print("=== Analyzing IQCommon/const.pyc - format_engine ===")
print("="*60)
pyc_path = 'site-packages/IQCommon/const.pyc'
orig_code = load_code_from_pyc(pyc_path)
decomp_source = decompile_pyc(pyc_path)
lines = decomp_source.split('\n')
while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
    lines.pop(0)
decomp_source = '\n'.join(lines)
decomp_code = compile(decomp_source, '<decompiled>', 'exec')

orig_funcs = {c.co_name: c for c in orig_code.co_consts if hasattr(c, 'co_code')}
decomp_funcs = {c.co_name: c for c in decomp_code.co_consts if hasattr(c, 'co_code')}

if 'format_engine' in orig_funcs and 'format_engine' in decomp_funcs:
    of = orig_funcs['format_engine']
    df = decomp_funcs['format_engine']
    print(f"\n--- ORIG format_engine bytecode (len={len(list(dis.get_instructions(of)))}) ---")
    for i, inst in enumerate(dis.get_instructions(of)):
        print(f"  [{i:3d}] {inst.offset:4d} {inst.opname:30s} {inst.argrepr}")
    print(f"\n--- DECOMP format_engine bytecode (len={len(list(dis.get_instructions(df)))}) ---")
    for i, inst in enumerate(dis.get_instructions(df)):
        print(f"  [{i:3d}] {inst.offset:4d} {inst.opname:30s} {inst.argrepr}")
    
    # Show decompiled source
    print("\n--- Decompiled source for format_engine context ---")
    src_lines = decomp_source.split('\n')
    in_func = False
    for line in src_lines:
        if 'def format_engine' in line:
            in_func = True
        if in_func:
            print(f"  {line}")
            if line.strip() and not line.startswith(' ') and not line.startswith('def'):
                break

