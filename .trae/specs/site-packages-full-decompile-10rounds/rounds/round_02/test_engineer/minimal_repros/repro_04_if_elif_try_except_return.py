"""Test pattern: if-elif with try-except and return in branch"""
import time
def test_func(date):
    try:
        if '-' in date:
            if len(date) != 10:
                return False
            time.strptime(date, '%Y-%m-%d')
        elif len(date) != 8:
            return False
        return True
    except:
        return False
