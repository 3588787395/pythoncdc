"""Test pattern: if-elif-else with try-except - JUMP_FORWARD to function end replaced with return True"""
import time

def isVaildDate(date):
    try:
        if '-' in date:
            if len(date) != 10:
                return False
            time.strptime(date, '%Y-%m-%d')
        elif len(date) != 8:
            return False
        else:
            time.strptime(date, '%Y%m%d')
        return True
    except:
        return False
