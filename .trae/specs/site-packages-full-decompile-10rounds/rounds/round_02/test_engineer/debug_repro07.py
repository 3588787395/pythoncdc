"""Debug repro_07: if-else with pass in both branches."""
import sys, os, marshal, dis

sys.path.insert(0, 'f:/Downloads/pythoncdc-main')
os.chdir('f:/Downloads/pythoncdc-main')
from pycdc import decompile_pyc

py_path = '.trae/specs/site-packages-full-decompile-10rounds/rounds/round_02/test_engineer/minimal_repros/repro_07_if_else_pass.py'
with open(py_path, 'r', encoding='utf-8') as f:
    source = f.read()

code = compile(source, py_path, 'exec')
pyc_path = py_path.replace('.py', '.pyc')
with open(pyc_path, 'wb') as f:
    f.write(b'\x6f\x0d\x0d\x0a')
    f.write(b'\x00\x00\x00\x00')
    f.write(b'\x00\x00\x00\x00')
    f.write(b'\x00\x00\x00\x00')
    marshal.dump(code, f)

decomp_source = decompile_pyc(pyc_path)
lines = decomp_source.split('\n')
while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
    lines.pop(0)
decomp_source = '\n'.join(lines)
decomp_code = compile(decomp_source, '<decompiled>', 'exec')

print("=== ORIGINAL SOURCE ===")
print(source)
print("\n=== DECOMPILED SOURCE ===")
print(decomp_source)

orig_func = [c for c in code.co_consts if hasattr(c, 'co_code') and c.co_name == 'test_func'][0]
decomp_func = [c for c in decomp_code.co_consts if hasattr(c, 'co_code') and c.co_name == 'test_func'][0]

print("\n=== ORIGINAL test_func BYTECODE ===")
for i, inst in enumerate(dis.get_instructions(orig_func)):
    print(f"  [{i:3d}] {inst.offset:4d} {inst.opname:30s} {inst.argrepr}")

print("\n=== DECOMPILED test_func BYTECODE ===")
for i, inst in enumerate(dis.get_instructions(decomp_func)):
    print(f"  [{i:3d}] {inst.offset:4d} {inst.opname:30s} {inst.argrepr}")
