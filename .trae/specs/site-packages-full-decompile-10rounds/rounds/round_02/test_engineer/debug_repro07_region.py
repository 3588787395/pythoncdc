"""Debug: check region types in repro_07."""
import sys, os, marshal, dis

sys.path.insert(0, 'f:/Downloads/pythoncdc-main')
os.chdir('f:/Downloads/pythoncdc-main')

py_path = '.trae/specs/site-packages-full-decompile-10rounds/rounds/round_02/test_engineer/minimal_repros/repro_07_if_else_pass.py'
with open(py_path, 'r', encoding='utf-8') as f:
    source = f.read()

code = compile(source, py_path, 'exec')
pyc_path = py_path.replace('.py', '.pyc')
with open(pyc_path, 'wb') as f:
    f.write(b'\x6f\x0d\x0d\x0a')
    f.write(b'\x00\x00\x00\x00')
    f.write(b'\x00\x00\x00\x00')
    f.write(b'\x00\x00\x00\x00')
    marshal.dump(code, f)

with open(pyc_path, 'rb') as f:
    f.read(16)
    code_obj = marshal.load(f)

from core.cfg.cfg_builder import CFGBuilder
from core.cfg.region_analyzer import RegionAnalyzer, IfRegion

cfg_builder = CFGBuilder()
cfg = cfg_builder.build(code_obj)
analyzer = RegionAnalyzer(cfg)
analyzer.analyze()

print(f"Total regions: {len(analyzer.regions)}")
for i, region in enumerate(analyzer.regions):
    print(f"\n=== Region {i}: {type(region).__name__} ===")
    print(f"  Module: {type(region).__module__}")
    print(f"  Bases: {[b.__name__ for b in type(region).__mro__]}")
    
    # Print all attributes
    for attr in sorted(dir(region)):
        if attr.startswith('_'):
            continue
        val = getattr(region, attr)
        if callable(val):
            continue
        if attr in ('blocks',):
            print(f"  {attr}: {[b.start_offset for b in val]}")
        elif attr in ('then_blocks', 'else_blocks', 'elif_bodies', 'elif_final_else', 'chained_compare_blocks'):
            if val:
                print(f"  {attr}: {[b.start_offset for b in val]}")
            else:
                print(f"  {attr}: None/[]")
        elif attr in ('condition_block', 'merge_block', 'entry', 'back_edge_block'):
            print(f"  {attr}: {val.start_offset if val else None}")
        else:
            print(f"  {attr}: {val}")

# Also check the test_func code object's sub-regions
func_code = [c for c in code_obj.co_consts if hasattr(c, 'co_code') and c.co_name == 'test_func'][0]
print(f"\n=== test_func code object ===")
print(f"  co_consts: {func_code.co_consts}")
print(f"  Instructions:")
for i, inst in enumerate(dis.get_instructions(func_code)):
    print(f"  [{i:3d}] {inst.offset:4d} {inst.opname:30s} {inst.argrepr}")

# Build CFG for test_func
cfg2 = cfg_builder.build(func_code)
analyzer2 = RegionAnalyzer(cfg2)
analyzer2.analyze()
print(f"\n=== test_func regions: {len(analyzer2.regions)} ===")
for i, region in enumerate(analyzer2.regions):
    print(f"\nRegion {i}: {type(region).__name__}")
    for attr in ['entry', 'condition_block', 'merge_block', 'back_edge_block']:
        val = getattr(region, attr, None)
        print(f"  {attr}: {val.start_offset if val else None}")
    for attr in ['then_blocks', 'else_blocks', 'elif_final_else']:
        val = getattr(region, attr, None)
        if val:
            print(f"  {attr}: {[b.start_offset for b in val]}")
        else:
            print(f"  {attr}: None/[]")
    elif_cond = getattr(region, 'elif_conditions', None)
    print(f"  elif_conditions: {bool(elif_cond)}")
