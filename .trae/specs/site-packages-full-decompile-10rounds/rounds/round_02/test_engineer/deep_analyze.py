from pycdc import decompile_pyc

def load_code_from_pyc(pyc_path):
    with open(pyc_path, 'rb') as f:
        f.read(16)
        return marshal.load(f)

def show_code_diff(orig_code, decomp_code, name="", max_diff=10):
    """Show detailed bytecode diff."""
    orig_instrs = list(dis.get_instructions(orig_code))
    decomp_instrs = list(dis.get_instructions(decomp_code))
    
    if orig_code.co_code == decomp_code.co_code:
        print(f"  {name}: MATCH")
        return
    
    print(f"\n  {name}: MISMATCH (orig={len(orig_instrs)}, decomp={len(decomp_instrs)})")
    diff_count = 0
    for i in range(max(len(orig_instrs), len(decomp_instrs))):
        o = orig_instrs[i] if i < len(orig_instrs) else None
        d = decomp_instrs[i] if i < len(decomp_instrs) else None
        if o is None:
            print(f"    [{i}] EXTRA: {d.opname} {d.argrepr}")
            diff_count += 1
        elif d is None:
            print(f"    [{i}] MISSING: {o.opname} {o.argrepr}")
            diff_count += 1
        elif o.opname != d.opname or o.arg != d.arg:
            print(f"    [{i}] ORIG: {o.opname} {o.argrepr}")
            print(f"    [{i}] DECP: {d.opname} {d.argrepr}")
            diff_count += 1
        if diff_count >= max_diff:
            print(f"    ... (truncated, more diffs)")
            break

