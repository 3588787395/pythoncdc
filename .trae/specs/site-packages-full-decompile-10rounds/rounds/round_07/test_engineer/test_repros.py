"""Round 07 最小复现集运行器。

对 minimal_repros/ 下每个 repro：
  1. 读源码，直接 compile(src) 得到原始 code object；
  2. 调 core.cfg.decompile(src) 得到反编译文本；
  3. compile(反编译文本) 得到新 code object；
  4. 用 compare_bytecode.compare_all 逐函数比较 co_code。
打印每个 repro 的 PASS/FAIL（FAIL 时给出首个差异指令），输出汇总统计。
预期（缺陷未修）：全部 FAIL；修复后必须全 PASS。
"""
import os
import sys

sys.path.insert(0, r'F:\Downloads\pythoncdc-main')
os.chdir(r'F:\Downloads\pythoncdc-main')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from core.cfg import decompile as decompile_src
import compare_bytecode as cb


def run_repro(py_path):
    """返回 (ok, 明细)。"""
    with open(py_path, 'r', encoding='utf-8') as f:
        src = f.read()

    try:
        orig_code = compile(src, py_path, 'exec')
    except SyntaxError as e:
        return False, f"原始源码编译失败: {e}"

    try:
        text = decompile_src(src)
    except Exception as e:
        return False, f"反编译异常: {type(e).__name__}: {e}"

    if not isinstance(text, str):
        return False, f"反编译返回非字符串: {type(text)!r}"

    try:
        decomp_code = cb.compile_decompiled_source(text)
    except SyntaxError as e:
        return False, f"反编译文本重编译失败: {e}"

    results, passed, total = cb.compare_all(orig_code, decomp_code)
    details = [f"{name}: {'PASS' if ok else 'FAIL - ' + detail}" for name, ok, detail in results]
    ok_all = passed == total
    return ok_all, '; '.join(details)


def main():
    repro_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'minimal_repros')
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'repro_results.txt')
    files = sorted(fn for fn in os.listdir(repro_dir)
                   if fn.endswith('.py') and not fn.startswith('__'))
    buf = [f"=== Round 07 repro 集运行: {len(files)} 个用例 ==="]
    passed_n = 0
    failed_n = 0
    for fn in files:
        py_path = os.path.join(repro_dir, fn)
        try:
            ok, detail = run_repro(py_path)
        except Exception as e:  # 单例失败不阻断整体
            ok, detail = False, f"运行器异常: {type(e).__name__}: {e}"
        if ok:
            passed_n += 1
            buf.append(f"[PASS] {fn}")
        else:
            failed_n += 1
            buf.append(f"[FAIL] {fn}")
            buf.append(f"       {detail}")
    total = passed_n + failed_n
    rate = passed_n / total if total else 0.0
    buf.append(f"\n=== SUMMARY: {passed_n}/{total} PASS ({rate:.3f}), {failed_n} FAIL ===")
    buf.append(f"说明: 当前为缺陷复现基线；根因 A/B 修复后必须全 PASS（12/12）。")
    report = '\n'.join(buf) + '\n'
    print(report)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(report)
    return failed_n


if __name__ == '__main__':
    sys.exit(0 if main() == 0 else 1)
