"""Round 07 字节码比较工具。

加载原 pyc（marshal，跳过 16 字节头），编译反编译源码（剥离 # 开头的头部行），
递归收集函数（co_name -> code），逐函数比较：
  - co_code 字节级相等
  - co_consts 相等（嵌套 code object 归一化为可比较结构，避免按身份比较误报）
  - co_exceptiontable 相等
输出每函数 PASS/FAIL 与总成功率。
"""
import dis
import marshal


def load_code_from_pyc(pyc_path):
    """加载 pyc：跳过 16 字节头后 marshal 反序列化。"""
    with open(pyc_path, 'rb') as f:
        f.read(16)
        return marshal.load(f)


def compile_decompiled_source(src):
    """剥离反编译输出头部（# 注释行与空行）后编译为 code object。"""
    if src.startswith('\ufeff'):
        src = src[1:]
    lines = src.split('\n')
    while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
        lines.pop(0)
    return compile('\n'.join(lines), '<decompiled>', 'exec')


def collect_funcs(code_obj, prefix=''):
    """递归收集 code object 及其嵌套函数，返回 {限定名: code}。"""
    out = {}
    name = f"{prefix}.{code_obj.co_name}" if prefix else code_obj.co_name
    out[name] = code_obj
    for c in code_obj.co_consts:
        if hasattr(c, 'co_code'):
            out.update(collect_funcs(c, name))
    return out


def norm_const(c):
    """归一化常量：code object -> 可比较元组；递归处理 tuple/frozenset。"""
    if hasattr(c, 'co_code'):
        return ('<CODE>', c.co_name,
                tuple(norm_const(x) for x in c.co_consts),
                bytes(c.co_code), bytes(c.co_exceptiontable))
    if isinstance(c, tuple):
        return tuple(norm_const(x) for x in c)
    return c


def first_const_diff(orig, decomp):
    """返回 co_consts 首个差异的描述（已排除嵌套 code 的身份比较干扰）。"""
    o = [norm_const(c) for c in orig.co_consts]
    d = [norm_const(c) for c in decomp.co_consts]
    if len(o) != len(d):
        return f"常量个数 {len(o)} vs {len(d)}"
    for i, (a, b) in enumerate(zip(o, d)):
        if a != b:
            sa, sb = repr(orig.co_consts[i]), repr(decomp.co_consts[i])
            return (f"const[{i}] 不同: orig={sa[:80]} vs decomp={sb[:80]}")
    return None


def first_code_diff(orig, decomp):
    """返回 co_code 的首个差异指令描述，完全相等时返回 None。"""
    orig_instrs = list(dis.get_instructions(orig))
    decomp_instrs = list(dis.get_instructions(decomp))
    n = max(len(orig_instrs), len(decomp_instrs))
    for i in range(n):
        o = orig_instrs[i] if i < len(orig_instrs) else None
        d = decomp_instrs[i] if i < len(decomp_instrs) else None
        if o is None:
            return f"多余指令: offset={d.offset} {d.opname} {d.argrepr}"
        if d is None:
            return f"缺失指令: offset={o.offset} {o.opname} {o.argrepr}"
        if o.opname != d.opname or o.arg != d.arg:
            return (f"[{i}] ORIG: offset={o.offset} {o.opname} {o.argrepr}"
                    f" | DECOMP: offset={d.offset} {d.opname} {d.argrepr}")
    return None


def compare_func(orig, decomp):
    """比较单个函数，返回 (ok, 明细信息)。"""
    diffs = []
    if orig.co_code != decomp.co_code:
        diff = first_code_diff(orig, decomp)
        diffs.append(f"co_code 不一致 ({len(orig.co_code)} vs {len(decomp.co_code)} 字节): {diff}")
    if norm_const(orig.co_consts) != norm_const(decomp.co_consts):
        diffs.append(f"co_consts 不一致 ({first_const_diff(orig, decomp)})")
    if orig.co_exceptiontable != decomp.co_exceptiontable:
        diffs.append(f"co_exceptiontable 不一致 ({len(orig.co_exceptiontable)} vs "
                     f"{len(decomp.co_exceptiontable)} 字节)")
    return (not diffs), '; '.join(diffs)


def compare_all(orig_code, decomp_code):
    """递归比较所有函数，返回 (结果列表[(名称, ok, 明细)], 通过数, 总数)。"""
    ofuncs = collect_funcs(orig_code)
    dfuncs = collect_funcs(decomp_code)
    results = []
    passed = 0
    for name in sorted(set(ofuncs) | set(dfuncs)):
        if name not in dfuncs:
            results.append((name, False, "反编译产物中缺失该函数"))
            continue
        if name not in ofuncs:
            results.append((name, False, "原 pyc 中缺失该函数"))
            continue
        ok, detail = compare_func(ofuncs[name], dfuncs[name])
        if ok:
            passed += 1
        results.append((name, ok, detail or 'match'))
    total = len(results)
    return results, passed, total


def compare_pyc_vs_source(pyc_path, decompiled_src, verbose=True):
    """完整流程：加载 pyc、编译反编译源码、逐函数比较。返回 (passed, total)。"""
    orig = load_code_from_pyc(pyc_path)
    decomp = compile_decompiled_source(decompiled_src)
    results, passed, total = compare_all(orig, decomp)
    if verbose:
        for name, ok, detail in results:
            print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {detail}")
        print(f"  === 成功率: {passed}/{total}")
    return passed, total
