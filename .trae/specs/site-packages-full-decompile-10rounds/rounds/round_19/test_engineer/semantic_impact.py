def load_pyc(path):
    with open(path, 'rb') as f:
        return marshal.loads(f.read()[16:])


def main_functions(code):
    """Yield (name, live function) for top-level functions (incl. methods)."""
    g = {'__builtins__': __builtins__}
    out = []
    for c in code.co_consts:
        if hasattr(c, 'co_code'):
            if c.co_name in ('<lambda>',) or True:
                fn = types.FunctionType(c, g, c.co_name)
                g[c.co_name] = fn
                out.append((c.co_name, fn))
    # class methods: find class code consts and bind
    return out


def run_pair(py_path, inputs):
    base = os.path.splitext(os.path.basename(py_path))[0]
    pyc = os.path.join(TMP, 'sem_' + base + '.pyc')
    py_compile.compile(py_path, cfile=pyc, doraise=True)
    orig_root = load_pyc(pyc)
    src = pycdc.decompile_pyc(pyc)
    dec_root = compile(src, '<decomp>', 'exec')

    ns1 = {}
    exec(compile(open(py_path, encoding='utf-8').read(), '<orig>', 'exec'), ns1)
    ns2 = {}
    exec(compile(src, '<decomp>', 'exec'), ns2)

    def collect(ns):
        d = {}
        for k, v in ns.items():
            if isinstance(v, types.FunctionType) and not k.startswith('_'):
                d[k] = v
            elif isinstance(v, type):
                for mk, mv in vars(v).items():
                    if isinstance(mv, types.FunctionType):
                        d['%s.%s' % (k, mk)] = mv.__get__(None, v)
        return d

    f1 = collect(ns1)
    f2 = collect(ns2)
    assert set(f1) == set(f2), 'function sets differ'

    print('== %s ==' % os.path.basename(py_path))
    all_same = True
    for label, args in inputs:
        try:
            r1 = list(f1.values())[0](*args)
        except Exception as e:
            r1 = '%s: %s' % (type(e).__name__, e)
        try:
            r2 = list(f2.values())[0](*args)
        except Exception as e:
            r2 = '%s: %s' % (type(e).__name__, e)
        same = repr(r1) == repr(r2)
        all_same &= same
        print('  input %-28s orig=%-34s decomp=%-34s %s'
              % (label, repr(r1)[:34], repr(r2)[:34],
                 'OK' if same else '*** SEMANTIC MISMATCH ***'))
    return all_same


