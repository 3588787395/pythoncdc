"""Round 19 Test Engineer: verify gtn_request.pyc decompilation + bytecode consistency.

Strict standard: raw co_code bytes must be exactly equal.
Also reports compare_bytecode() results per function for reference.
"""
import io
import marshal
import os
import sys
import dis

sys.path.insert(0, r'F:\Downloads\pythoncdc-main')

import pycdc
from testqouter.round1.base import compare_bytecode

PYC = r'F:\Downloads\pythoncdc-main\site-packages\IQData\plugins\plugin_system_gtn_request\gtn_request.pyc'
OUT_DIR = r'D:\Temp\opencode\r19_test'


def load_pyc_code(path):
    with open(path, 'rb') as f:
        data = f.read()
    return marshal.loads(data[16:])


def walk_functions(code, prefix=''):
    """Yield (qualified_name, code) for every code object except the module."""
    qual = (prefix + '.' + code.co_name) if prefix else code.co_name
    results = []
    if code.co_name != '<module>':
        results.append((qual, code))
    for const in code.co_consts:
        if hasattr(const, 'co_code'):
            results.extend(walk_functions(const, qual))
    return results


def dump_dis(code):
    buf = io.StringIO()
    for ins in dis.get_instructions(code):
        line = 'offset=%4d opname=%-28s argrepr=%s\n' % (
            ins.offset, ins.opname, repr(ins.argval)[:80])
        buf.write(line)
    return buf.getvalue()


def instr_at(code, offset):
    for ins in dis.get_instructions(code):
        if ins.offset == offset:
            return ins
    return None


def instr_list(code):
    return list(dis.get_instructions(code))


def main():
    orig_root = load_pyc_code(PYC)

    try:
        source = pycdc.decompile_pyc(PYC)
    except Exception as e:
        print('CRASH: decompile_pyc raised: %r' % e)
        import traceback
        traceback.print_exc()
        sys.exit(2)

    with open(os.path.join(OUT_DIR, 'gtn_request_decompiled.py'), 'w',
              encoding='utf-8') as f:
        f.write(source)

    try:
        dec_root = compile(source, '<decomp>', 'exec')
    except SyntaxError as e:
        print('SYNTAX_FAIL: recompile failed: %s' % e)
        sys.exit(3)

    orig_funcs = dict(walk_functions(orig_root))
    dec_funcs = dict(walk_functions(dec_root))

    rows = []
    mismatch_files = []
    for name, ocode in orig_funcs.items():
        dcode = dec_funcs.get(name)
        row = {
            'name': name,
            'orig_len': len(ocode.co_code),
            'dec_len': None,
            'strict': False,
            'cmp_match': None,
            'first_diff_offset': None,
            'context': [],
        }
        if dcode is None:
            row['note'] = 'MISSING in decompiled output'
            rows.append(row)
            continue
        row['dec_len'] = len(dcode.co_code)
        row['strict'] = (ocode.co_code == dcode.co_code)
        cmp_res = compare_bytecode(ocode, dcode)
        row['cmp_match'] = bool(cmp_res['match'])
        row['true_diffs'] = len(cmp_res.get('true_diffs', []))
        row['jump_diffs'] = len(cmp_res.get('jump_diffs', []))

        if not row['strict']:
            oi = instr_list(ocode)
            di = instr_list(dcode)
            first_off = None
            n = max(len(oi), len(di))
            for i in range(n):
                a = oi[i] if i < len(oi) else None
                b = di[i] if i < len(di) else None
                if a is None or b is None or a.opname != b.opname or a.argval != b.argval:
                    first_off = i
                    break
            row['first_diff_index'] = first_off
            if first_off is not None:
                lo = max(0, first_off - 5)
                hi_a = min(len(oi), first_off + 6)
                hi_b = min(len(di), first_off + 6)
                ctx = []
                for j in range(lo, hi_a):
                    ctx.append(('orig', j, oi[j]))
                ctx.append(('---', first_off, '<<< FIRST DIFF >>>'))
                for j in range(lo, hi_b):
                    ctx.append(('decomp', j, di[j]))
                row['context'] = ctx

            fname_safe = name.replace('.', '__')
            opath = os.path.join(OUT_DIR, 'orig_dis.txt')
            dpath = os.path.join(OUT_DIR, 'dec_dis.txt')
            with open(opath, 'a', encoding='utf-8') as f:
                f.write('===== FUNCTION %s =====\n' % name)
                f.write(dump_dis(ocode) + '\n')
            with open(dpath, 'a', encoding='utf-8') as f:
                f.write('===== FUNCTION %s =====\n' % name)
                f.write(dump_dis(dcode) + '\n')
            mismatch_files.append(name)
        rows.append(row)

    extra = set(dec_funcs) - set(orig_funcs)
    print('=' * 100)
    print('PYC : %s' % PYC)
    print('co_names(module) functions found: orig=%d decomp=%d'
          % (len(orig_funcs), len(dec_funcs)))
    if extra:
        print('EXTRA functions in decompiled output: %s' % sorted(extra))
    print('=' * 100)
    hdr = '%-40s %8s %8s %-7s %-9s %-10s %-9s %s'
    print(hdr % ('FUNCTION', 'orig_byt', 'dec_byt', 'STRICT', 'CMP_MATCH',
                 'true_diffs', 'jump_dif', 'first_diff_idx'))
    pass_strict = 0
    for r in rows:
        mark = 'PASS' if r['strict'] else 'FAIL'
        if r['strict']:
            pass_strict += 1
        print(hdr % (r['name'], r['orig_len'],
                     r['dec_len'] if r['dec_len'] is not None else '-',
                     mark,
                     str(r['cmp_match']),
                     str(r.get('true_diffs', '-')),
                     str(r.get('jump_diffs', '-')),
                     str(r.get('first_diff_index', '-'))))
    total = len(rows)
    print('-' * 100)
    print('STRICT co_code equality: %d/%d functions PASS (%.0f%%)'
          % (pass_strict, total, 100.0 * pass_strict / max(total, 1)))

    for r in rows:
        if r['strict']:
            continue
        print('=' * 100)
        print('DETAIL: %s  (orig %s bytes vs decomp %s bytes)' %
              (r['name'], r['orig_len'], r['dec_len']))
        for side, idx, item in r['context']:
            if side == '---':
                print('     %s' % item)
            else:
                ins = item
                print('  [%s #%d] off=%4d %-26s argval=%s'
                      % (side, idx, ins.offset, ins.opname,
                         repr(ins.argval)[:70]))

    print('=' * 100)
    print('dis dumps written to:')
    for fn in ('orig_dis.txt', 'dec_dis.txt'):
        print('  %s' % os.path.join(OUT_DIR, fn))
    print('functions dumped: %s' % mismatch_files)


if __name__ == '__main__':
    main()
