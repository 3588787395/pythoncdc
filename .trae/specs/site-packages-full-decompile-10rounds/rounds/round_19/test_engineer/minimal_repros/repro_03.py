# repro_03 [FAIL-family: nested-in-else with try/except preceding the chain]
# Mirrors send_service's try/json.loads context before the failing chain.
import json as _json


def process(raw):
    try:
        tmp = _json.loads(raw)
    except TypeError:
        tmp = raw
    data = tmp['data']
    if isinstance(data, list):
        rsp = data
    elif 'k' in data:
        return ('k',)
    else:
        if 'rows' in data:
            rsp = data['rows']
        elif 'd' in data:
            if 'x' in data['d']:
                return ('x',)
            else:
                rsp = data['d']
        else:
            return []
    return list(rsp)
