# repro_13 [ADJACENT-family: for loop + return in middle arm]
# `return None` demoted to `break`; spurious `continue` added to else arm.
def scan(items):
    out = []
    for it in items:
        if it is None:
            return None
        elif it < 0:
            break
        else:
            out.append(it)
    return out
