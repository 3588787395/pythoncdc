# Single-level chain with bare-return final else + inner if/else in the
# middle arm (no OUTER chain wrapping). Isolates: one nesting level is not
# sufficient; repro_01 needs the chain-inside-chain arrangement.
def process(data):
    if 'rows' in data:
        rsp = data['rows']
    elif 'data' in data:
        if 'last_tradeday' in data['data']:
            return ['lastday']
        else:
            rsp = data['data']
    else:
        return []
    return list(rsp)
