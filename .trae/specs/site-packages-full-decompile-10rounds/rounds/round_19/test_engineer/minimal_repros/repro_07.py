# repro_07 [FAIL-family: nested-in-else + ternary assignment inside arm]
def process(data):
    if isinstance(data, list):
        rsp = data
    elif 'k' in data:
        return ('k',)
    else:
        if 'rows' in data:
            rsp = data['rows']
        elif 'd' in data:
            rsp = data['d'] if data['d'] else ['empty']
            if 'x' in data['d']:
                return ('x',)
        else:
            return []
    return list(rsp)
