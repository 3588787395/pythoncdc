# 4-arm chain, return arms at positions 1 and 3 (r,a,r | else-r).
# Same family as repro_09/10/11 but this layout survives roundtrip.
def grade(score):
    if score >= 90:
        return 'A'
    elif score >= 80:
        g = 'B'
    elif score >= 70:
        return 'C'
    else:
        return 'F'
    return 'grade:' + g
