# repro_04 [FAIL-family: nested-in-else inside a class method]
class Worker:
    def process(self, data):
        if isinstance(data, list):
            rsp = data
        elif 'k' in data:
            return ('k',)
        else:
            if 'rows' in data:
                rsp = data['rows']
            elif 'd' in data:
                if 'x' in data['d']:
                    return ('x',)
                else:
                    rsp = data['d']
            else:
                return []
        return list(rsp)
