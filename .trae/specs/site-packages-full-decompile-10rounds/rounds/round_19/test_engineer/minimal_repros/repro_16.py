# Flat 3-arm chain with bare-return FINAL else but NO nesting and no return
# arm before the last condition. Isolates: bare-return-final-else alone does
# NOT trigger the truncation.
def flat(d):
    if 'p' in d:
        v = d['p']
    elif 'q' in d:
        v = d['q'] + 1
    else:
        return 0
    return v
