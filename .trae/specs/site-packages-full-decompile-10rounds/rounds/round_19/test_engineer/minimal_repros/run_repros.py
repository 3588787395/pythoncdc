# -*- coding: utf-8 -*-
"""Batch-run minimal repros: compile -> pyc -> decompile_pyc -> recompile ->
strict co_code comparison. Prints PASS/FAIL/CRASH list with first-diff info.
Saves each decompiled source next to the repro for evidence.
"""
import marshal
import os
import sys
import time
import py_compile

sys.path.insert(0, r'F:\Downloads\pythoncdc-main')

import pycdc

HERE = os.path.dirname(os.path.abspath(__file__))
PYC_TMP = os.path.join(HERE, '_tmp_pyc')
os.makedirs(PYC_TMP, exist_ok=True)


def load_pyc_code(path):
    with open(path, 'rb') as f:
        data = f.read()
    return marshal.loads(data[16:])


def walk_functions(code):
    out = [(code.co_name, code)]
    for c in code.co_consts:
        if hasattr(c, 'co_code'):
            out.extend(walk_functions(c))
    return out


def instr_list(code):
    import dis
    return list(dis.get_instructions(code))


def run_one(py_path):
    name = os.path.basename(py_path)
    base = os.path.splitext(name)[0]
    pyc_path = os.path.join(PYC_TMP, base + '.pyc')
    rec = {'name': name, 'status': 'PASS', 'funcs': [], 'error': None}

    try:
        py_compile.compile(py_path, cfile=pyc_path, doraise=True)
        orig_root = load_pyc_code(pyc_path)
    except Exception as e:
        rec['status'] = 'SETUP_FAIL'
        rec['error'] = repr(e)
        return rec

    try:
        src = pycdc.decompile_pyc(pyc_path)
    except Exception as e:
        rec['status'] = 'CRASH'
        rec['error'] = '%s: %s' % (type(e).__name__, e)
        return rec

    with open(os.path.join(HERE, 'decomp_' + base + '.py'), 'w',
              encoding='utf-8') as f:
        f.write(src)

    try:
        dec_root = compile(src, '<decomp>', 'exec')
    except SyntaxError as e:
        rec['status'] = 'SYNTAX_FAIL'
        rec['error'] = str(e)
        return rec

    orig_funcs = dict(walk_functions(orig_root))
    dec_funcs = dict(walk_functions(dec_root))

    for fname, ocode in orig_funcs.items():
        dcode = dec_funcs.get(fname)
        fr = {'func': fname,
              'orig_len': len(ocode.co_code),
              'dec_len': None, 'strict': False}
        if dcode is None:
            fr['note'] = 'missing'
            rec['status'] = 'FAIL'
            rec['funcs'].append(fr)
            continue
        fr['dec_len'] = len(dcode.co_code)
        fr['strict'] = (ocode.co_code == dcode.co_code)
        if not fr['strict']:
            oi = instr_list(ocode)
            di = instr_list(dcode)
            n = max(len(oi), len(di))
            for i in range(n):
                a = oi[i] if i < len(oi) else None
                b = di[i] if i < len(di) else None
                if a is None or b is None or a.opname != b.opname \
                        or a.argval != b.argval:
                    ao = '%s@%d' % (a.opname, a.offset) if a else '<EOF>'
                    bo = '%s@%d' % (b.opname, b.offset) if b else '<EOF>'
                    fr['first_diff'] = '#%d orig[%s] vs decomp[%s]' % (i, ao, bo)
                    break
            rec['status'] = 'FAIL'
        rec['funcs'].append(fr)

    extra = set(dec_funcs) - set(orig_funcs)
    if extra:
        rec['extra_funcs'] = sorted(extra)
        rec['status'] = 'FAIL'
    return rec


def main():
    repros = sorted(
        os.path.join(HERE, f) for f in os.listdir(HERE)
        if f.startswith('repro_') and f.endswith('.py'))
    rows = []
    for rp in repros:
        t0 = time.time()
        rec = run_one(rp)
        rec['secs'] = time.time() - t0
        rows.append(rec)

    print('=' * 120)
    print('%-14s %-6s %s' % ('REPRO', 'RESULT', 'DETAIL'))
    print('-' * 120)
    n_fail = 0
    for r in rows:
        detail = '; '.join(
            '%s: %d->%s%s%s' % (f['func'], f['orig_len'],
                                f['dec_len'] if f['dec_len'] is not None else '-',
                                '' if f['strict'] else ' DIFF(' +
                                f.get('first_diff', 'mismatch') + ')',
                                (' ' + f['note']) if 'note' in f else '')
            for f in r['funcs'])
        if r.get('error'):
            detail += '  [err=%s]' % r['error']
        if 'extra_funcs' in r:
            detail += '  [extra funcs: %s]' % r['extra_funcs']
        mark = r['status']
        if mark == 'FAIL':
            n_fail += 1
        print('%-14s %-6s %.1fs  %s' % (r['name'], mark, r['secs'], detail))
    print('-' * 120)
    total = len(rows)
    n_pass = total - n_fail
    print('TOTAL: %d repros | FAIL(before fix): %d | PASS(regression baseline): %d '
          '| pre-fix reproduction rate: %.0f%%'
          % (total, n_fail, n_pass, 100.0 * n_fail / max(total, 1)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
