def process(lv, data):
    if lv == 0:
        if isinstance(data, list):
            rsp = data
        elif 'k' in data:
            return ('k',)
        else:
            if 'rows' in data:
                rsp = data['rows']
            elif 'd' in data:
                if 'x' in data['d']:
                    if len(data['d']) > 2:
                        return ('deep',)
                    else:
                        rsp = data['d']
                else:
                    rsp = ['dd']
            else:
                return []
        return list(rsp)
    return None
