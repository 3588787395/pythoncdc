# repro_02 [FAIL-family: nested-in-else at depth+1]
# Same skeleton as repro_01 but the whole chain is wrapped in one more `if`,
# so the chain merge is not the function end.
def process(flag, data):
    if flag:
        if isinstance(data, list):
            rsp = data
        elif 'k' in data:
            return ('k',)
        else:
            if 'rows' in data:
                rsp = data['rows']
            elif 'd' in data:
                if 'x' in data['d']:
                    return ('x',)
                else:
                    rsp = data['d']
            else:
                return []
        return list(rsp)
    return None
