# -*- coding: utf-8 -*-
"""Direct trace evidence for W17-B: run decompile_pyc under sys.settrace and
record every _check_elif_chain invocation/return inside region_analyzer.py,
specifically whether the guard at line 15307 (`len(first_else.conditional_successors)
!= 2`) fires and returns None at line 15308.
Run against a FAIL repro (repro_01) and a PASS baseline (repro_17) for contrast.
No project code is modified - runtime tracing only.
"""
import marshal
import os
import py_compile
import sys
import time

sys.path.insert(0, r'F:\Downloads\pythoncdc-main')

RA_PATH = os.path.normpath(r'F:\Downloads\pythoncdc-main\core\cfg\region_analyzer.py')
OUT = r'D:\Temp\opencode\r19_test\trace_evidence.txt'

TARGET_FN = '_check_elif_chain'
GUARD_LINE = 15307      # if len(first_else.conditional_successors) != 2:
BAIL_LINE = 15308       # return None
CTRL_EXIT_LINE = 15280  # return None (then_has_ctrl_exit path)
NO_ELSE_LINE = 15199    # return None (no else blocks)

LOG = []


def load_pyc(path):
    with open(path, 'rb') as f:
        return marshal.loads(f.read()[16:])


def make_tracer(tag):
    state = {'depth': 0}

    def local_tracer(frame, event, arg):
        if frame.f_code.co_filename != RA_PATH:
            return None
        co_name = frame.f_code.co_name
        if event == 'line':
            ln = frame.f_lineno
            if ln == GUARD_LINE:
                fe = frame.f_locals.get('first_else')
                ncs = len(fe.conditional_successors) if fe is not None else None
                LOG.append('[%s] LINE %d GUARD first_else.cond_succ=%s'
                           % (tag, ln, ncs))
            elif ln in (BAIL_LINE, CTRL_EXIT_LINE, NO_ELSE_LINE):
                LOG.append('[%s] LINE %d EARLY_RETURN_NONE' % (tag, ln))
        if event == 'return':
            if co_name == TARGET_FN:
                rv = 'None' if arg is None else '<elif_info>'
                LOG.append('[%s] RET -> %s' % (tag, rv))
        return local_tracer

    return local_tracer


def run_case(tag, py_path):
    LOG.clear()
    base = os.path.splitext(os.path.basename(py_path))[0]
    pyc = os.path.join(r'D:\Temp\opencode\r19_test\_trace', base + '.pyc')
    os.makedirs(os.path.dirname(pyc), exist_ok=True)
    py_compile.compile(py_path, cfile=pyc, doraise=True)

    import pycdc
    t0 = time.time()
    sys.settrace(lambda frame, event, arg: _dispatch(frame, event, arg, tag))
    try:
        src = pycdc.decompile_pyc(pyc)
    finally:
        sys.settrace(None)
    secs = time.time() - t0
    compile(src, '<decomp>', 'exec')

    lines = list(LOG)
    calls = sum(1 for l in lines if 'CALL' in l)
    guards = [(i, l) for i, l in enumerate(lines) if 'GUARD' in l]
    bails = sum(1 for l in lines if l.endswith('EARLY_RETURN_NONE'))
    bail_at_15308 = sum(1 for l in lines if 'LINE 15308' in l)

    out = []
    out.append('#' * 90)
    out.append('CASE %s (%s)  decompile time %.1fs (traced)' % (tag, py_path, secs))
    out.append('_check_elif_chain CALLs          : %d' % calls)
    out.append('guard line %d evaluations         : %d' % (GUARD_LINE, len(guards)))
    out.append('early `return None` exits (all)   : %d' % bails)
    out.append('bails specifically at line %d     : %d' % (BAIL_LINE, bail_at_15308))
    out.append('')
    out.append('-- full event log --')
    out.extend(lines)
    return '\n'.join(out)


def _dispatch(frame, event, arg, tag):
    if frame.f_code.co_filename == RA_PATH:
        if event == 'call' and frame.f_code.co_name == TARGET_FN:
            eb = frame.f_locals.get('else_blocks_') or []
            cs = [len(b.conditional_successors) for b in eb]
            LOG.append('[%s] CALL else_blocks=%d cond_succ=%s'
                       % (tag, len(eb), cs))
        return make_tracer(tag)
    return None


def main():
    parts = []
    parts.append(run_case('repro_01 [EXPECT FAIL - W17-B shape]',
                          r'D:\Temp\opencode\r19_test\minimal_repros\repro_01.py'))
    parts.append(run_case('repro_09 [EXPECT FAIL - flat 5-arm]',
                          r'D:\Temp\opencode\r19_test\minimal_repros\repro_09.py'))
    parts.append(run_case('repro_17 [BASELINE PASS]',
                          r'D:\Temp\opencode\r19_test\minimal_repros\repro_17.py'))
    text = '\n\n'.join(parts)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text + '\n')
    # console summary
    for chunk in parts:
        for line in chunk.splitlines():
            if not line.startswith(('-', '[')):
                print(line)
        print()
    print('full log -> %s' % OUT)


if __name__ == '__main__':
    main()
