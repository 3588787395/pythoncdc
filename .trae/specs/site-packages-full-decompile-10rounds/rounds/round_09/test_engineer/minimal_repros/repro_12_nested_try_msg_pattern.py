def k(src, p):
    try:
        exec_code(src, p)
    except Exception as e:
        log()
        try:
            msg = str(e)
        except Exception as ex:
            log()
            msg = ''
            show(ex)
        err = mk()
        err.set(msg)
        if e.kind == 1:
            err.note(e.f, e.l, '', e.t)
        else:
            for it in its:
                if p == it[0]:
                    err.add(*it)
        if err.n == 0:
            err.add(*it)
        raise Wrap(err)
