"""R09-11 星号调用 + 循环变量泄漏：尾随 if 使用最后一次迭代的 item。

缺陷形态：`error.add_stack_info(*item)` 中 item 是循环泄漏变量，
尾随 `if error.stacks_length == 0:` 在 except handler 内被丢弃
（compile_help.pyc 偏移 876-916 的核心特征，含 LOAD_CONST 0 缺失）。
"""


def h(items, path):
    try:
        run(path)
    except Exception:
        stackinfos = list(extract())
        for item in stackinfos:
            filename, lineno = item
            if path == filename:
                error.add_stack_info(*item)
        if error.stacks_length == 0:
            error.add_stack_info(*item)
        raise UserError(error)
