# -*- coding: utf-8 -*-
"""R09 diagnostic: trace region generation order."""
import sys

PROJ = r'F:\Downloads\pythoncdc-main'
sys.path.insert(0, PROJ)

from core.cfg import build_cfg
import core.cfg.region_ast_generator as rag


orig_gr = rag.RegionASTGenerator._generate_region


def traced(self, region):
    en = getattr(region, 'entry', None)
    cb = getattr(region, 'condition_block', None)
    hdr = getattr(region, 'header_block', None)
    depth = len(self._generating_regions)
    print('%s_generate_region %s entry=%s cond=%s hdr=%s' % (
        '  ' * depth, type(region).__name__,
        en.start_offset if en is not None else None,
        cb.start_offset if cb is not None else None,
        hdr.start_offset if hdr is not None else None))
    return orig_gr(self, region)


rag.RegionASTGenerator._generate_region = traced

repro = sys.argv[1]
with open(repro, encoding='utf-8') as f:
    src = f.read()

code_obj = compile(src, '<r>', 'exec')
fns = [c for c in code_obj.co_consts if hasattr(c, 'co_code')]
fn = fns[0]

cfg = build_cfg(fn)
gen = rag.RegionASTGenerator(cfg)
gen.generate()
