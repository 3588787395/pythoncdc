# -*- coding: utf-8 -*-
"""R09 diagnostic: dump raw try regions before/after coalescing."""
import sys

PROJ = r'F:\Downloads\pythoncdc-main'
sys.path.insert(0, PROJ)

from core.cfg import build_cfg
import core.cfg.region_analyzer as ra

orig_identify = ra.RegionAnalyzer._identify_try_except_regions
orig_coalesce = ra.RegionAnalyzer._coalesce_split_try_except_finally_regions


def show(tag, regions):
    print('==== %s' % tag)
    for r in regions:
        if type(r).__name__ != 'TryExceptRegion':
            continue
        tb = getattr(r, 'try_blocks', None)
        hb = getattr(r, 'handler_blocks', None)
        fb = getattr(r, 'finally_blocks', None)
        en = getattr(r, 'entry', None)
        print('  Try entry=%s try=%s handler=%s finally=%s has_finally=%r' % (
            en.start_offset if en is not None else None,
            sorted(b.start_offset for b in tb) if tb else None,
            sorted(b.start_offset for b in hb) if hb else None,
            sorted(b.start_offset for b in fb) if fb else None,
            getattr(r, 'has_finally', None)))


def traced_id(self):
    res = orig_identify(self)
    show('identify_try_except_regions', res)
    return res


def traced_co(self, try_regions):
    res = orig_coalesce(self, try_regions)
    show('after_coalesce', res)
    return res


ra.RegionAnalyzer._identify_try_except_regions = traced_id
ra.RegionAnalyzer._coalesce_split_try_except_finally_regions = traced_co

repro = sys.argv[1]
with open(repro, encoding='utf-8') as f:
    src = f.read()

code_obj = compile(src, '<r>', 'exec')
fns = [c for c in code_obj.co_consts if hasattr(c, 'co_code')]
fn = fns[0]

cfg = build_cfg(fn)
analyzer = ra.RegionAnalyzer(cfg)
analyzer.analyze()
