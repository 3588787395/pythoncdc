# -*- coding: utf-8 -*-
"""R09 diagnostic: dump region structure for a repro file (per function)."""
import sys

PROJ = r'F:\Downloads\pythoncdc-main'
sys.path.insert(0, PROJ)

from core.cfg import build_cfg
import core.cfg.region_ast_generator as rag

repro = sys.argv[1]
with open(repro, encoding='utf-8') as f:
    src = f.read()

code_obj = compile(src, '<r>', 'exec')
fns = [c for c in code_obj.co_consts if hasattr(c, 'co_code')]
fn = fns[0]

cfg = build_cfg(fn)
gen = rag.RegionASTGenerator(cfg)
ast_dict = gen.generate()
regions = getattr(gen, 'regions', [])
print('region count:', len(regions))
for r in regions:
    eb = getattr(r, 'else_blocks', None)
    mb = getattr(r, 'merge_block', None)
    en = getattr(r, 'entry_block', None)
    hdr = getattr(r, 'header_block', None)
    cb = getattr(r, 'condition_block', None)
    fie = None
    try:
        fie = r.metadata.get('for_iter_exit')
        fis = r.metadata.get('for_iter_setup')
    except Exception:
        fis = None
    print('-', type(r).__name__,
          'entry=', en.start_offset if en else None,
          ('hdr=%d' % hdr.start_offset) if hdr else '',
          ('cond=%d' % cb.start_offset) if cb else '',
          ('merge=%d' % mb.start_offset) if mb else 'merge=None',
          'blocks=', sorted(b.start_offset for b in r.blocks),
          'orelse_blocks=', sorted(b.start_offset for b in eb) if eb is not None else None,
          ('fie=%s' % fie.start_offset) if fie is not None else '',
          ('fis=%s' % fis.start_offset) if fis is not None else '')
print()
print('block map:')
for b in sorted(cfg.blocks.values(), key=lambda x: x.start_offset):
    last = b.instructions[-1] if b.instructions else None
    ops = [i.opname for i in b.instructions]
    print('  blk@%3d: %-40s | last %s->%s | succ=%s' % (
        b.start_offset, ','.join(ops[:6]),
        last.opname if last else '-', last.argval if last else '-',
        sorted(s.start_offset for s in b.successors)))
