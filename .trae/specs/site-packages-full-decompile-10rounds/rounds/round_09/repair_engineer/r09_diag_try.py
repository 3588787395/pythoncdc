# -*- coding: utf-8 -*-
"""R09 diagnostic: dump TryExceptRegion internals."""
import sys

PROJ = r'F:\Downloads\pythoncdc-main'
sys.path.insert(0, PROJ)

from core.cfg import build_cfg
from core.cfg.region_analyzer import RegionAnalyzer

repro = sys.argv[1]
with open(repro, encoding='utf-8') as f:
    src = f.read()

code_obj = compile(src, '<r>', 'exec')
fns = [c for c in code_obj.co_consts if hasattr(c, 'co_code')]
fn = fns[0]

cfg = build_cfg(fn)
analyzer = RegionAnalyzer(cfg)
regions = analyzer.analyze()

for r in regions:
    if type(r).__name__ != 'TryExceptRegion':
        continue
    print('TryExceptRegion:')
    for attr in ('entry', 'merge_block',):
        v = getattr(r, attr, None)
        print('  %s=%s' % (attr, v.start_offset if v is not None else None))
    for attr in ('try_blocks', 'handler_blocks', 'finally_blocks', 'else_blocks',
                 'children', 'blocks'):
        v = getattr(r, attr, None)
        if v is None:
            print('  %s=None' % attr)
        elif isinstance(v, (list, set)):
            try:
                print('  %s=%s' % (attr, sorted(
                    b.start_offset for b in v if hasattr(b, 'start_offset'))))
            except TypeError:
                print('  %s=%r' % (attr, v))
        else:
            print('  %s=%r' % (attr, v))
    print('  has_finally=%r' % getattr(r, 'has_finally', None))
