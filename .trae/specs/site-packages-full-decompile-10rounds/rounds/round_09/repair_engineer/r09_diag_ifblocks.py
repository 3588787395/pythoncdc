# -*- coding: utf-8 -*-
"""R09 diagnostic: dump IfRegion branch blocks."""
import sys

PROJ = r'F:\Downloads\pythoncdc-main'
sys.path.insert(0, PROJ)

from core.cfg import build_cfg
from core.cfg.region_analyzer import RegionAnalyzer

repro = sys.argv[1]
with open(repro, encoding='utf-8') as f:
    src = f.read()

code_obj = compile(src, '<r>', 'exec')
fns = [c for c in code_obj.co_consts if hasattr(c, 'co_code')]
fn = fns[0]

cfg = build_cfg(fn)
analyzer = RegionAnalyzer(cfg)
regions = analyzer.analyze()

for r in regions:
    if type(r).__name__ != 'IfRegion':
        continue
    en = getattr(r, 'entry', None)
    cb = getattr(r, 'condition_block', None)
    mb = getattr(r, 'merge_block', None)
    tb = getattr(r, 'then_blocks', None)
    eb = getattr(r, 'else_blocks', None) or getattr(r, 'orelse_blocks', None)
    print('IfRegion entry=%s cond=%s merge=%s' % (
        en.start_offset if en else None,
        cb.start_offset if cb else None,
        mb.start_offset if mb else None))
    print('  then_blocks:', [b.start_offset for b in tb] if tb else None)
    print('  else_blocks:', [b.start_offset for b in eb] if eb else None)
