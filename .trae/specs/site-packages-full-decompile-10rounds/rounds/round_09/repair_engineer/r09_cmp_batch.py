# -*- coding: utf-8 -*-
"""Compare two batch result JSONs for regressions."""
import json
import sys

a_path, b_path = sys.argv[1], sys.argv[2]
with open(a_path, encoding='utf-8') as f:
    a = json.load(f)
with open(b_path, encoding='utf-8') as f:
    b = json.load(f)


def norm(d):
    out = {}
    items = d.get('results') or d.get('files') or d
    if isinstance(items, dict):
        for k, v in items.items():
            if isinstance(v, dict):
                out[k] = v
            else:
                out[k] = {'matched': v}
    elif isinstance(items, list):
        for v in items:
            k = v.get('file') or v.get('path') or v.get('name')
            out[k] = v
    return out


na, nb = norm(a), norm(b)
keys = set(na) | set(nb)


def is_full(v):
    if not isinstance(v, dict):
        return bool(v)
    fu, ma = v.get('funcs'), v.get('matched')
    if fu is None:
        return bool(v.get('full_match'))
    return ma == fu


declined = []
lost_full = []
improved = []
gained_full = []
for k in sorted(keys):
    va, vb = na.get(k), nb.get(k)
    ma = (va or {}).get('matched', 0)
    mb = (vb or {}).get('matched', 0)
    if mb > ma:
        improved.append((k, ma, mb))
    elif mb < ma:
        declined.append((k, ma, mb))
    if is_full(va) and not is_full(vb):
        lost_full.append(k)
    if not is_full(va) and is_full(vb):
        gained_full.append(k)

print('files compared:', len(keys))
print('full-match A:', sum(1 for k in keys if is_full(na.get(k))))
print('full-match B:', sum(1 for k in keys if is_full(nb.get(k))))
print()
print('LOST FULL MATCH (%d):' % len(lost_full))
for k in lost_full:
    print('  !', k)
print('DECLINED func count (%d):' % len(declined))
for k, ma, mb in declined:
    print('  -', k, ':', ma, '->', mb)
print('GAINED FULL MATCH (%d):' % len(gained_full))
for k in gained_full:
    print('  +', k)
print('IMPROVED func count (%d):' % len(improved))
for k, ma, mb in improved:
    print('  +', k, ':', ma, '->', mb)
