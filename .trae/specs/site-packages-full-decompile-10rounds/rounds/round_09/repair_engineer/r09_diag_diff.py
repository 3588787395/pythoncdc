"""R09 diagnostic: full co_code + exception table diff for repro_07."""
import sys
import dis

PROJ = r'F:\Downloads\pythoncdc-main'
sys.path.insert(0, PROJ)
R07 = PROJ + r'\.trae\specs\site-packages-full-decompile-10rounds\rounds\round_07\test_engineer'
sys.path.insert(0, R07)

from compare_bytecode import compile_decompiled_source, collect_funcs
from core.cfg import decompile

repro = sys.argv[1]
with open(repro, encoding='utf-8') as f:
    src = f.read()

orig = compile(src, '<r>', 'exec')
dec_src = decompile(src)
new = compile_decompiled_source(dec_src)


def dump(orig, new, tag):
    of = collect_funcs(orig)['f']
    nf = collect_funcs(new)['f']
    print('==== %s' % tag)
    print('-- orig code (f) --')
    for i in dis.get_instructions(of):
        print('%4d %s %r' % (i.offset, i.opname, i.argval))
    print('-- dec code (f) --')
    for i in dis.get_instructions(nf):
        print('%4d %s %r' % (i.offset, i.opname, i.argval))
    print('-- orig extab --', list(of.co_exceptiontable))
    print('-- dec extab --', list(nf.co_exceptiontable))


orig_f = [c for c in orig.co_consts if hasattr(c, 'co_code')][0]
new_top = compile_decompiled_source(dec_src)
new_f = [c for c in new_top.co_consts if hasattr(c, 'co_code')][0]
dump(orig_f, new_f, 'diff')
