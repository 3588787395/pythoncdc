"""Helper to compile a source module to a .pyc, decompile it, recompile the
decompiled output, and compare per-function bytecode (mirrors tools.bc_cmp).

Used by the round_27 test_engineer analysis to validate minimal repros.
"""
import os
import sys
import marshal
import types
import dis

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))  # F:/Downloads/pythoncdc-main
sys.path.insert(0, ROOT)

from pycdc import decompile_pyc
from testqouter.round1.base import compare_bytecode


def make_pyc(src, pyc_path):
    co = compile(src, "<repro>", "exec")
    with open(pyc_path, "wb") as f:
        # Python 3.7+ 16-byte header: magic(4) + bit_field(4) + mtime(4) + source_size(4)
        import importlib.util
        f.write(importlib.util.MAGIC_NUMBER)
        f.write((0).to_bytes(4, "little"))      # bit field (no hash)
        f.write((0).to_bytes(4, "little"))      # mtime
        f.write((len(src)).to_bytes(4, "little"))  # source size
        f.write(marshal.dumps(co))


def iter_code_objects(code, prefix=""):
    name = prefix + code.co_name if prefix else code.co_name
    yield name, code
    for const in code.co_consts:
        if isinstance(const, types.CodeType):
            sub = name + "." if name != "<module>" else ""
            yield from iter_code_objects(const, sub)


def run_src(src, pyc_path=None):
    """Compile src -> pyc, decompile, recompile, compare. Returns (ok, details)."""
    import tempfile
    if pyc_path is None:
        pyc_path = os.path.join(tempfile.gettempdir(), "_repro_tmp.pyc")
    make_pyc(src, pyc_path)
    dec = decompile_pyc(pyc_path)
    try:
        decomp_code = compile(dec, "<decompiled>", "exec")
    except SyntaxError as e:
        return False, {"syntax_error": str(e), "decompiled": dec}
    with open(pyc_path, "rb") as f:
        orig_code = marshal.loads(f.read()[16:])
    funcs = {}
    ok_all = True
    for (oname, ocode), (dname, dcode) in zip(
        iter_code_objects(orig_code), iter_code_objects(decomp_code)
    ):
        if oname != dname:
            funcs[oname] = (False, {"name_mismatch": dname})
            ok_all = False
            continue
        res = compare_bytecode(ocode, dcode)
        ok = bool(res.get("match"))
        funcs[oname] = (ok, {
            "orig_count": res.get("orig_count"),
            "decomp_count": res.get("decomp_count"),
            "true_diffs": res.get("true_diffs") or [],
        })
        if not ok:
            ok_all = False
    return ok_all, {"funcs": funcs, "decompiled": dec}


if __name__ == "__main__":
    import sys
    src = sys.stdin.read()
    ok, det = run_src(src)
    print("OK" if ok else "FAIL")
    if not ok:
        for fn, (fok, fd) in det.get("funcs", {}).items():
            if not fok:
                print("  func", fn, "diffs:", len(fd.get("true_diffs", [])))
                for d in fd.get("true_diffs", [])[:6]:
                    print("    ", d)
