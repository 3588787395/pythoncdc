# EXC-2 (except (A, B) tuple + trailing return): the canonical failing shape seen in
#   PositionDict.__missing__ (finance.pyc). A `try` whose conditional branches `return`,
#   an `except (AttributeError, KeyError): raise ...` handler, and a `return` placed
#   AFTER the handler (the compiler hoists it out of the try region). pycdc (a) drops
#   one of the exception types from the tuple and (b) re-nests the trailing return
#   inside the try.
