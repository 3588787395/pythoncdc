#       raise KeyError('missing')
#   return Position(self, symbol)
# Observed: decompiled emits `except KeyError:` (type dropped) and re-nests the final
#   `return Position(...)` inside the try; recompiled bytecode diverges at the
#   JUMP_FORWARD/PUSH_EXC_INFO/BUILD_TUPLE/CHECK_EXC_MATCH boundary (verified identical
#   to the real __missing__ diff).
class Position(object):
    def __init__(self, e, s):
        pass

def g(s):
    return s

class PD(dict):
    def __missing__(self, symbol):
        try:
            symbol = g(symbol)
            r = self.get(symbol, None)
            if r is not None:
                return r
            symbol = symbol.replace('X', 'Y')
            r = self.get(symbol, None)
            if r is not None:
                return r
        except (AttributeError, KeyError):
            raise KeyError('missing')
        return Position(self, symbol)
