# EXC-1 (with-based, nested): `with` whose body contains a nested `try/except`
#   wrapped by an outer catch-all `except:`.
# Expected: try: with open(p) as fh: try: return fh.read() except ValueError: return b''
#          except: return None
# Observed: decompiled handler placement is wrong (PUSH_EXC_INFO/POP_EXCEPT/RERAISE
#   structure diverges), so recompiled bytecode does not match the original.
def f(path):
    try:
        with open(path) as fh:
            try:
                return fh.read()
            except ValueError:
                return b''
    except:
        return None
