# EXC-4 (try inside `while` loop, `continue` in handler): a `try/except` whose body
#   `return`s and whose handler `continue`s the enclosing infinite `while` loop. The
#   RERAISE/POP_EXCEPT boundary at the loop head is mishandled by pycdc.
# Expected:
#   while True:
#       try:
#           return q.get()
#       except ValueError:
#           continue
# Observed: decompiled recompiled bytecode diverges (loop re-entry / handler placement
#   wrong).
def f(q):
    while True:
        try:
            return q.get()
        except ValueError:
            continue
