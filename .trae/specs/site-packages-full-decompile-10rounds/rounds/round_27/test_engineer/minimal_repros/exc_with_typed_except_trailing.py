# EXC-1 (with-based, typed except + trailing return): `with` inside `try` with a
#   typed `except` and a statement AFTER the try/except that the compiler hoists
#   outside the handler region. pycdc re-nests that trailing return inside the try.
# Expected:
#   try:
#       with open(path) as fh:
#           data = fh.read()
#           if data:
#               return data
#           return fh.read()
#   except OSError:
#       return None
#   return b'x'
# Observed: decompiled recompiled bytecode does not match (handler / trailing-return
#   placement diverges; WITH_EXCEPT_START + CHECK_EXC_MATCH + RERAISE region shifted).
def f(path):
    try:
        with open(path) as fh:
            data = fh.read()
            if data:
                return data
            return fh.read()
    except OSError:
        return None
    return b'x'
