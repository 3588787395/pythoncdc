# EXC-4 (try inside `while` loop, `except` + `else/break`): variant where the
#   `try/except` sits in a `while` loop and the handler falls through to an `else:
#   break`. Control flow at the loop boundary is mishandled.
# Expected:
#   while True:
#       try:
#           return q.get()
#       except ValueError:
#           continue
#       else:
#           break
# Observed: decompiled recompiled bytecode diverges.
def f(q):
    while True:
        try:
            return q.get()
        except ValueError:
            continue
        else:
            break
