# EXC-1 (with-based, bare except): `with` inside `try` with a catch-all `except:`.
# Expected: try: with open(p) as fh: return fh.read() except: return None
# Observed (pycdc): recompiled bytecode loses the RERAISE / POP_EXCEPT tail of the
#   with-exception handler (WITH_EXCEPT_START + PUSH_EXC_INFO + POP_EXCEPT + RERAISE),
#   so non-`with`-related exceptions get silently swallowed instead of propagating.
def f(path):
    try:
        with open(path) as fh:
            return fh.read()
    except:
        return None
