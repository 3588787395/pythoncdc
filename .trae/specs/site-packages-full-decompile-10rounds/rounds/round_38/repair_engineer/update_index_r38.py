"""R38: update pyc_index.json for the two newly-ok files (round 38)."""
import json
import shutil
from collections import Counter

IDX = 'F:/Downloads/pythoncdc-main/pyc_index.json'
shutil.copy(IDX, 'F:/Downloads/pythoncdc-main/pyc_index.json.bak_r38')
idx = json.load(open(IDX, encoding='utf-8'))
targets = {
    'IQEngine/account/base_position.pyc': (18, 18),
    'IQCommon/data/local_finance.pyc': (19, 19),
}
changed = 0
for e in idx:
    p = e['path'].replace('\\', '/')
    for suffix, (m, t) in targets.items():
        if p.endswith(suffix):
            e['decompile_status'] = 'ok'
            e['bytecode_match_rate'] = 1.0
            e['match_rate'] = 1.0
            e['ok_py_generated'] = True
            e['last_tested_round'] = 38
            e['matched_functions'] = m
            e['total_functions'] = t
            e['mismatch_count'] = 0
            print('updated:', suffix)
            changed += 1
json.dump(idx, open(IDX, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('updated entries:', changed)
print('status:', Counter(e['decompile_status'] for e in json.load(open(IDX, encoding='utf-8'))))
