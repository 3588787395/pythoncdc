"""R37: update pyc_index.json for the two newly-ok files (round 37)."""
import json
import shutil
from collections import Counter

IDX = 'F:/Downloads/pythoncdc-main/pyc_index.json'
shutil.copy(IDX, 'F:/Downloads/pythoncdc-main/pyc_index.json.bak_r37')
idx = json.load(open(IDX, encoding='utf-8'))
targets = {
    'IQEngine/plugins/plugin_fly_data/fly_api/order_api_trade.pyc': (24, 24),
    'IQEngine/plugins/plugin_system_trade/send_message_api.pyc': (4, 4),
}
changed = 0
for e in idx:
    p = e['path'].replace('\\', '/')
    for suffix, (m, t) in targets.items():
        if p.endswith(suffix):
            e['decompile_status'] = 'ok'
            e['bytecode_match_rate'] = 1.0
            e['match_rate'] = 1.0
            e['ok_py_generated'] = True
            e['last_tested_round'] = 37
            e['matched_functions'] = m
            e['total_functions'] = t
            e['mismatch_count'] = 0
            print('updated:', suffix, m, '/', t)
            changed += 1
json.dump(idx, open(IDX, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('updated entries:', changed)
print('status:', Counter(e['decompile_status'] for e in json.load(open(IDX, encoding='utf-8'))))
