"""R36: merge slice scans and compare per-file against the r35 baseline."""
import json
import os
import glob

R36 = os.path.dirname(os.path.abspath(__file__))
BASE = (r'F:/Downloads/pythoncdc-main'
        r'/.trae/specs/site-packages-full-decompile-10rounds'
        r'/rounds/round_36/repair_engineer/scan_after_fix_r36.json')


def norm(p):
    return os.path.normcase(os.path.normpath(p.replace('\\', '/')))


def main():
    cur = {}
    for f in sorted(glob.glob(os.path.join(R36, 'scan_r37_part_*.json'))):
        data = json.load(open(f, encoding='utf-8'))
        for rec in data['results']:
            cur[norm(rec['path'])] = rec
    base = {}
    data = json.load(open(BASE, encoding='utf-8'))
    for rec in data['results']:
        base[norm(rec['path'])] = rec

    print('current files:', len(cur), 'baseline files:', len(base))
    regress, improve = [], []
    for p, r in cur.items():
        b = base.get(p)
        if not b:
            continue
        if (r['matched_functions'] < b['matched_functions']
                or (b['status'] == 'ok' and r['status'] != 'ok')):
            regress.append((p, b['status'], r['status'],
                            b['matched_functions'], r['matched_functions']))
        elif (r['matched_functions'] > b['matched_functions']
                or (b['status'] != 'ok' and r['status'] == 'ok')):
            improve.append((p, b['status'], r['status'],
                            b['matched_functions'], r['matched_functions']))
    print('REGRESSIONS:', len(regress))
    for p in regress:
        print('  ', p)
    print('IMPROVEMENTS:', len(improve))
    for p in improve:
        print('  ', p)
    s_ok = sum(1 for r in cur.values() if r['status'] == 'ok')
    s_part = sum(1 for r in cur.values() if r['status'] == 'partial')
    s_fail = sum(1 for r in cur.values() if r['status'] == 'failed')
    mf = sum(r['matched_functions'] for r in cur.values())
    tf = sum(r['total_functions'] for r in cur.values())
    print(f'TOTAL: ok={s_ok} partial={s_part} failed={s_fail} funcs={mf}/{tf}')
    json.dump({'summary': {'ok': s_ok, 'partial': s_part, 'failed': s_fail,
                           'matched_functions': mf, 'total_functions': tf},
               'results': list(cur.values())},
              open(os.path.join(R36, 'scan_after_fix_r37.json'), 'w',
                   encoding='utf-8'), ensure_ascii=False, indent=1)


if __name__ == '__main__':
    main()
