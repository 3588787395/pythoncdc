def f(security, market_type, amount, log, build):
    if security == '1':
        if market_type not in (0, 1):
            log('x')
            return None
    elif security == '2':
        if market_type is None:
            market_type = 0
        if market_type not in (0, 2):
            log('y')
            return None
    else:
        log('z')
        return None
    if amount > 0:
        d = build('BUY')
    elif amount < 0:
        d = build('SELL')
        amount = -amount
    else:
        log('zero')
        return None
    return build(d, amount)
