def f(x, y, log):
    if x == '1':
        if y:
            log('a')
            return None
    elif x == '2':
        if y:
            log('b')
            return None
    else:
        log('c')
        return None
    if y > 2:
        d = 1
    elif y > 1:
        d = 2
    elif y > 0:
        d = 3
    else:
        log('d')
        return None
    return d
