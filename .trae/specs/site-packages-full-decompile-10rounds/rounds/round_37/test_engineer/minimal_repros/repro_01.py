def order_like(security, market_type, amount, log):
    if security == '1':
        if market_type is None:
            market_type = 0
        if market_type > 5:
            log('a')
            return None
    elif security == '2':
        if market_type is None:
            market_type = 0
        if market_type > 5:
            log('b')
            return None
    else:
        log('c')
        return None
    if amount > 0:
        d = 1
    elif amount < 0:
        d = 2
        amount = -amount
    else:
        log('d')
        return None
    return d
