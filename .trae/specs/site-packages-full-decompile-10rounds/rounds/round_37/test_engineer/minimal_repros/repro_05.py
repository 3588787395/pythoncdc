# Repro 05: three-branch outer chain, two fall through
def f(x, y, log):
    if x == '1':
        if y:
            log('a')
            return None
    elif x == '2':
        if y:
            log('b')
            return None
    elif x == '3':
        if y:
            log('c')
            return None
    else:
        log('d')
        return None
    if y > 0:
        d = 1
    elif y < 0:
        d = 2
    else:
        log('e')
        return None
    return d
