#!/usr/bin/env python3
"""R36 repro harness: compile each repro source, decompile, compare bytecode per function.

Usage: python run_repros.py [repro_dir]
"""
import os
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = r'F:/Downloads/pythoncdc-main'
sys.path.insert(0, ROOT)

from core.cfg import decompile
from testqouter.round1.base import compare_bytecode


def iter_code(code, prefix=''):
    name = (prefix + '.' + code.co_name) if prefix else code.co_name
    yield name, code
    for c in code.co_consts:
        if isinstance(c, types.CodeType):
            sub = name if name != '<module>' else ''
            yield from iter_code(c, sub)


def run_repro(path):
    with open(path, encoding='utf-8') as f:
        src = f.read()
    try:
        out = decompile(src)
    except Exception as e:
        return False, f'DECOMPILE CRASH: {e}'
    try:
        compiled = compile(out, '<decomp>', 'exec')
    except SyntaxError as e:
        return False, f'SYNTAX ERROR: {e}\n--- output ---\n{out}'
    orig = compile(src, '<orig>', 'exec')
    fails = []
    for name, code in iter_code(orig):
        m = None
        for n2, c2 in iter_code(compiled):
            if n2 == name:
                m = c2
                break
        if m is None:
            fails.append(f'{name}: MISSING in decompiled')
            continue
        r = compare_bytecode(code, m)
        if not r.get('match', r.get('is_match', True)):
            fails.append(f"{name}: orig={r.get('orig_count')} decomp={r.get('decomp_count')} diffs={r.get('diffs', r.get('true_diffs'))}")
    if fails:
        return False, ' | '.join(fails) + '\n--- output ---\n' + out
    return True, out


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'minimal_repros')
    files = sorted(f for f in os.listdir(d) if f.endswith('.py'))
    npass = 0
    for fn in files:
        ok, msg = run_repro(os.path.join(d, fn))
        print(f"[{'PASS' if ok else 'FAIL'}] {fn}")
        if not ok:
            for line in msg.splitlines()[:6]:
                print('    ' + line)
        else:
            npass += 1
    print(f"SUMMARY: {npass}/{len(files)} PASS")


if __name__ == '__main__':
    main()
