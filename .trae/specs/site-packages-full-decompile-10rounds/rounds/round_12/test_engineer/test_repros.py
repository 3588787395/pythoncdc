"""Round 12 最小复现实例运行器。

流程（与 R11 一致）：每个 repro 依次
  1. compile() 得原始 code object（基准）；
  2. core.cfg.decompile(src) 反编译；
  3. 剥离 # 头部行后 re-compile()；
  4. 递归收集函数，逐函数比较 co_code 字节、co_consts（归一化）、co_exceptiontable
     （复用 round_07 compare_bytecode 工具）。

结果写入 repro_results.txt 并打印 SUMMARY。

W12 缺陷家族（wrapper.pyc 残留，详见 ../decompile_report.md）：
  A 组（repro_01~05, 04b）：except 属性链截断——LOAD_ATTR 成分被丢弃只留根名；
  B 组（repro_04b）：BUILD_TUPLE 元组内各元素分别截断；
  C 组（repro_06, 07）：非 Name 根（下标/调用）退化为裸 except:（语义反转级）；
  D 组（repro_08, 09）：多 handler 链中属性表达式截断 + 偏移连带漂移；
  E 组（repro_10, 11）：wrapper.pyc api_exec_patcher.wrapper 同构复刻与闭包装饰器变体；
  F 组（repro_12）：裸名/裸名元组回归守卫（当前应 PASS）。
修复目标：13/13 文件全 PASS。
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = r'F:\Downloads\pythoncdc-main'
R07 = os.path.join(PROJ, '.trae', 'specs', 'site-packages-full-decompile-10rounds',
                   'rounds', 'round_07', 'test_engineer')
sys.path.insert(0, PROJ)
sys.path.insert(0, R07)

from compare_bytecode import (collect_funcs, norm_const, first_code_diff,  # noqa: E402
                              first_const_diff)
from core.cfg import decompile  # noqa: E402

REPRO_DIR = os.path.join(HERE, 'minimal_repros')
RESULT_FILE = os.path.join(HERE, 'repro_results.txt')


def compare_full(orig_top, decomp_top):
    """逐函数比较 co_code/co_consts/co_exceptiontable，返回 (passed, total, [(名, ok, 明细)])。"""
    ofuncs = collect_funcs(orig_top)
    dfuncs = collect_funcs(decomp_top)
    results = []
    passed = 0
    for name in sorted(set(ofuncs) | set(dfuncs)):
        if name not in dfuncs:
            results.append((name, False, '反编译产物中缺失该函数'))
            continue
        if name not in ofuncs:
            results.append((name, False, '原源码中缺失该函数'))
            continue
        o, d = ofuncs[name], dfuncs[name]
        diffs = []
        if o.co_code != d.co_code:
            diffs.append(f'co_code 不一致 ({len(o.co_code)} vs {len(d.co_code)} 字节): '
                         f'{first_code_diff(o, d)}')
        if norm_const(o.co_consts) != norm_const(d.co_consts):
            diffs.append(f'co_consts 不一致 ({first_const_diff(o, d)})')
        if o.co_exceptiontable != d.co_exceptiontable:
            diffs.append(f'co_exceptiontable 不一致 ({len(o.co_exceptiontable)} vs '
                         f'{len(d.co_exceptiontable)} 字节)')
        if diffs:
            results.append((name, False, '; '.join(diffs)))
        else:
            passed += 1
            results.append((name, True, 'match'))
    return passed, len(results), results


def run_repro(path):
    """跑单个 repro：compile → decompile → re-compile → 比较。返回 (ok, 输出行)。"""
    name = os.path.basename(path)
    lines = [f'=== {name} ===']
    with open(path, encoding='utf-8') as f:
        src = f.read()
    try:
        orig_top = compile(src, '<orig:' + name + '>', 'exec')
    except SyntaxError as e:
        lines.append(f'  [ERROR] 基准源码无法编译: {e}')
        return False, lines
    try:
        dec = decompile(src)
    except Exception as e:  # noqa: BLE001
        lines.append(f'  [ERROR] decompile 异常: {type(e).__name__}: {e}')
        return False, lines
    try:
        decomp_top = compile(dec, '<re:' + name + '>', 'exec')
    except SyntaxError as e:
        lines.append(f'  [ERROR] 反编译输出无法 re-compile: {e}')
        return False, lines
    passed, total, results = compare_full(orig_top, decomp_top)
    ok = passed == total
    for fname, fok, detail in results:
        lines.append(f"  [{'PASS' if fok else 'FAIL'}] {fname}: {detail}")
    lines.append(f'  --- {name}: {passed}/{total} functions {"PASS" if ok else "FAIL"}')
    return ok, lines


def main():
    repros = sorted(p for p in os.listdir(REPRO_DIR) if p.endswith('.py'))
    all_lines = []
    per_file = []
    files_ok = 0
    func_passed = 0
    func_total = 0
    for rp in repros:
        ok, lines = run_repro(os.path.join(REPRO_DIR, rp))
        npass = sum(1 for ln in lines if '[PASS]' in ln)
        nfail = sum(1 for ln in lines if '[FAIL]' in ln)
        func_passed += npass
        func_total += npass + nfail
        per_file.append((rp, ok, npass, npass + nfail))
        files_ok += int(ok)
        all_lines.extend(lines)
        all_lines.append('')

    header = [
        '# Round 12 repro_results.txt',
        '# 运行阶段：修复前基线（W12 家族未修复）',
        f'# 文件级: {files_ok}/{len(repros)} all-pass | 函数级: {func_passed}/{func_total} PASS',
        '',
    ]
    summary = [
        '================ SUMMARY ================',
        f'files all-pass : {files_ok}/{len(repros)}',
        f'functions PASS : {func_passed}/{func_total}',
        'per-file:',
    ]
    for rp, ok, np_, nt in per_file:
        summary.append(f'  [{"PASS" if ok else "FAIL"}] {rp} ({np_}/{nt})')
    out = '\n'.join(header + all_lines + summary) + '\n'
    with open(RESULT_FILE, 'w', encoding='utf-8') as f:
        f.write(out)
    print('\n'.join(summary))
    return 0


if __name__ == '__main__':
    sys.exit(main())
