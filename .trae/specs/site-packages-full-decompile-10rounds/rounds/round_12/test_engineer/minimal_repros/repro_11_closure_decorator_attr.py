"""W12-E 闭包+装饰器形态：属性截断在闭包 cell 变量上下文中同样发生。
预期缺陷：except mod.Err: → except mod:
"""
import functools

mod = None


def outer(mod_ref):
    def patcher(fn):
        @functools.wraps(fn)
        def w(*args, **kwargs):
            try:
                return fn(*args, **kwargs)
            except mod_ref.Err:
                raise
            except BaseException as e:
                if isinstance(e, TypeError):
                    return None
                raise
        return w
    return patcher
