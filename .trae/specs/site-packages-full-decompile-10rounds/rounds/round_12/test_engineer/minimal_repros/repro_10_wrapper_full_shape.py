import functools
import inspect
import sys
import types


class const:
    NEED_EXCEPTION_HANDLE = '_need_exc_'

    class ExcType:
        NOTSET = 'NOTSET'


class exception:
    IQInvalidArgument = type('IQInvalidArgument', (Exception,), {})

    class user_exc(Exception):
        pass

    class system_exc(Exception):
        pass

    @staticmethod
    def get_func_exc_ext_name_value(e):
        return 'NOTSET'


class utils:
    @staticmethod
    def get_original_function(f):
        return f


def get_traceback_message():
    return ''


system_log = type('L', (), {'error': staticmethod(lambda m: None)})()


def decorate_api_exc(func):
    f = func
    while f:
        if getattr(f, const.NEED_EXCEPTION_HANDLE, False):
            break
        f = getattr(f, '__wrapped__', None)
    else:
        func = api_exec_patcher(func)
    return func


def api_exec_patcher(func):
    if isinstance(func, types.FunctionType):
        @functools.wraps(func)
        def wrapper(*args, **kwargs):
            try:
                return func(*(args), **(kwargs))
            except exception.IQInvalidArgument:
                system_log.error('异常信息: %s' % get_traceback_message())
                raise
            except BaseException as e:
                system_log.error('异常信息: %s' % get_traceback_message())
                if isinstance(e, TypeError):
                    exc_info = sys.exc_info()
                    try:
                        inspect.signature(utils.get_original_function(func)).bind(*(args), **(kwargs))
                    except TypeError:
                        system_log.error('异常信息: %s' % get_traceback_message())
                        t, v, tb = exc_info
                        raise exception.user_exc(v.with_traceback(tb))
                if exception.get_func_exc_ext_name_value(e) == const.ExcType.NOTSET:
                    raise exception.system_exc(e)
                return None
        return wrapper
    else:
        return func
