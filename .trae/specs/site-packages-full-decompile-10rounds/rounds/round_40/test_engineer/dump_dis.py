#!/usr/bin/env python3
"""Dump disassembly of specific functions from backtest_info_utils.pyc."""
import dis
import marshal
import sys
import types

PYC = r'F:/Downloads/pythoncdc-main/site-packages/IQCommon/util/backtest_info_utils.pyc'

with open(PYC, 'rb') as f:
    code = marshal.loads(f.read()[16:])


def iter_code(c, prefix=''):
    name = (prefix + '.' + c.co_name) if prefix else c.co_name
    yield name, c
    for k in c.co_consts:
        if isinstance(k, types.CodeType):
            yield from iter_code(k, name)


targets = sys.argv[1:] if len(sys.argv) > 1 else [
    'add_end_flag', 'creat_sheet2', 'backtest_download_result']
for name, c in iter_code(code):
    if any(t in name for t in targets):
        print('=' * 70)
        print(f'CODE OBJECT: {name}  (len={len(c.co_code)})')
        print('=' * 70)
        dis.dis(c, depth=0)
        print()
