#!/usr/bin/env python3
"""R40 repro harness: compile each repro source, decompile, compare bytecode per function.

结构参照 round_39/test_engineer/run_repros.py：compile 源 → pyc 路径反编译
（compile → 写临时 .pyc → decompile_pyc）→ compile 输出 → 逐函数字节码对比。
R40 三个根因（merge 后继误嵌套 / while 出口 BFS 越界 / 三元 merge 块吞并）
均在 pyc 路径（区域识别对已有字节码分类）触发，故仅走 pyc 路径。

Usage: python run_repros.py [repro_dir]
"""
import importlib.util
import marshal
import os
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = r'F:/Downloads/pythoncdc-main'
sys.path.insert(0, ROOT)

from pycdc import decompile_pyc
from testqouter.round1.base import compare_bytecode


def iter_code(code, prefix=''):
    name = (prefix + '.' + code.co_name) if prefix else code.co_name
    yield name, code
    for c in code.co_consts:
        if isinstance(c, types.CodeType):
            sub = name if name != '<module>' else ''
            yield from iter_code(c, sub)


def _compare(orig, out, fails):
    compiled = compile(out, '<decomp>', 'exec')
    for name, code in iter_code(orig):
        m = None
        for n2, c2 in iter_code(compiled):
            if n2 == name:
                m = c2
                break
        if m is None:
            fails.append(f'{name}: MISSING in decompiled')
            continue
        r = compare_bytecode(code, m)
        if not r.get('match', r.get('is_match', True)):
            fails.append(f"{name}: orig={r.get('orig_count')} decomp={r.get('decomp_count')} diffs={r.get('diffs', r.get('true_diffs'))}")


def run_repro(path):
    with open(path, encoding='utf-8') as f:
        src = f.read()
    orig = compile(src, '<orig>', 'exec')

    # pyc 反编译路径（R40 缺陷触发路径）；临时 pyc 复用固定路径、不删除
    # （避免触发批量删除守卫，反编译器按 16 字节头加载不校验剩余内容）
    pyc = os.path.join(HERE, '_tmp_repro.pyc')
    try:
        with open(pyc, 'wb') as f:
            f.write(importlib.util.MAGIC_NUMBER)
            f.write(b'\x00' * 12)
            marshal.dump(orig, f)
        out = decompile_pyc(pyc)
    finally:
        pass
    try:
        fails = []
        _compare(orig, out, fails)
    except SyntaxError as e:
        return False, f'SYNTAX ERROR(pyc path): {e}\n--- output ---\n{out}'
    if fails:
        return False, ' | '.join(fails) + '\n--- output ---\n' + out

    return True, out


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'minimal_repros')
    files = sorted(f for f in os.listdir(d) if f.endswith('.py'))
    npass = 0
    results = []
    for fn in files:
        ok, msg = run_repro(os.path.join(d, fn))
        results.append((fn, ok))
        print(f"[{'PASS' if ok else 'FAIL'}] {fn}")
        if not ok:
            for line in msg.splitlines()[:6]:
                print('    ' + line)
        else:
            npass += 1
    print(f"SUMMARY: {npass}/{len(files)} PASS")
    # 机器可读基线
    with open(os.path.join(HERE, 'repro_baseline.txt'), 'w', encoding='utf-8') as f:
        for fn, ok in results:
            f.write(f"{'PASS' if ok else 'FAIL'} {fn}\n")
        f.write(f"SUMMARY: {npass}/{len(files)} PASS\n")


if __name__ == '__main__':
    main()
