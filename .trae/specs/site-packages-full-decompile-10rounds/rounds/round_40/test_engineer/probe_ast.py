#!/usr/bin/env python3
"""R40 instrumentation: dump generated AST (dict) for a target function."""
import json
import marshal
import sys
import types

ROOT = r'F:/Downloads/pythoncdc-main'
sys.path.insert(0, ROOT)

from core.cfg import build_cfg
from core.cfg.region_ast_generator import RegionASTGenerator

PYC = r'F:/Downloads/pythoncdc-main/site-packages/IQCommon/util/backtest_info_utils.pyc'

with open(PYC, 'rb') as f:
    module_code = marshal.loads(f.read()[16:])


def iter_code(c, prefix=''):
    name = (prefix + '.' + c.co_name) if prefix else c.co_name
    yield name, c
    for k in c.co_consts:
        if isinstance(k, types.CodeType):
            yield from iter_code(k, name)


def compact(node, depth=0, maxdepth=14):
    if not isinstance(node, dict):
        return ' ' * depth + repr(node)[:100] + '\n'
    t = node.get('type', '?')
    out = ' ' * depth + t
    if 'name' in node or 'id' in node:
        out += f" {node.get('name') or node.get('id')}"
    if node.get('value') is not None and not isinstance(node.get('value'), (dict, list)):
        out += f" = {node['value']!r}"[:120]
    out += '\n'
    if depth > maxdepth:
        return out
    for k, v in node.items():
        if k in ('type',):
            continue
        if isinstance(v, dict):
            out += ' ' * (depth + 2) + f'[{k}]\n'
            out += compact(v, depth + 4, maxdepth)
        elif isinstance(v, list):
            out += ' ' * (depth + 2) + f'[{k}] x{len(v)}\n'
            for it in v:
                out += compact(it, depth + 4, maxdepth)
    return out


def main():
    targets = sys.argv[1:] or ['add_end_flag']
    for name, c in iter_code(module_code):
        if name.split('.')[-1] not in targets:
            continue
        cfg = build_cfg(c)
        gen = RegionASTGenerator(cfg, parent_code=c, top_level_code=module_code)
        ast_dict = gen.generate()
        with open(f"ast_" + name.replace('.', '_').replace('<', '').replace('>', '') + '.json', 'w', encoding='utf-8') as f:
            json.dump(ast_dict, f, ensure_ascii=False, indent=1, default=str)
        body = ast_dict.get('body') if isinstance(ast_dict, dict) else None
        if body:
            for stmt in body:
                print(compact(stmt))


if __name__ == '__main__':
    main()
