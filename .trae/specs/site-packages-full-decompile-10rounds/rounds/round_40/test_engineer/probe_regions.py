#!/usr/bin/env python3
"""R40 instrumentation: dump region classification tree for target functions.

For each target function:
  1. build CFG from the original code object
  2. run RegionAnalyzer.analyze()
  3. print region tree: region type, entry/merge/body block offsets, block ranges
  4. print blocks never claimed by any region (orphans)
"""
import marshal
import sys
import types

ROOT = r'F:/Downloads/pythoncdc-main'
sys.path.insert(0, ROOT)

from core.cfg import build_cfg, CFGRegionAnalyzer

PYC = r'F:/Downloads/pythoncdc-main/site-packages/IQCommon/util/backtest_info_utils.pyc'

with open(PYC, 'rb') as f:
    module_code = marshal.loads(f.read()[16:])


def iter_code(c, prefix=''):
    name = (prefix + '.' + c.co_name) if prefix else c.co_name
    yield name, c
    for k in c.co_consts:
        if isinstance(k, types.CodeType):
            yield from iter_code(k, name)


def dump_regions(regions, analyzer, depth=0):
    for r in regions:
        entry = getattr(r, 'entry_block', None)
        merge = getattr(r, 'merge_block', None)
        blocks = sorted(b.start_offset for b in r.get_content_blocks())
        line = '  ' * depth
        line += f'{type(r).__name__} entry={entry.start_offset if entry else None}'
        if merge is not None:
            line += f' merge={merge.start_offset}'
        for attr in ('then_blocks', 'else_blocks', 'body_blocks', 'handler_blocks'):
            v = getattr(r, attr, None)
            if v:
                try:
                    line += f' {attr}={sorted(b.start_offset for b in v)}'
                except TypeError:
                    line += f' {attr}={v}'
        line += f' content={blocks}'
        print(line)
        if r.children:
            dump_regions(r.children, analyzer, depth + 1)


def main():
    targets = sys.argv[1:] or ['backtest_download_result']
    for name, c in iter_code(module_code):
        if name.split('.')[-1] not in targets:
            continue
        print('#' * 78)
        print(f'# CODE: {name}')
        print('#' * 78)
        cfg = build_cfg(c)
        analyzer = CFGRegionAnalyzer(cfg)
        regions = analyzer.analyze()
        claimed = set(analyzer.block_to_region.keys())
        dump_regions(regions, analyzer)
        all_blocks = sorted(b.start_offset for b in cfg.get_blocks() if b is not None)
        orphans = [o for o in all_blocks if o not in claimed]
        print(f'\nTOTAL_BLOCKS={len(all_blocks)} CLAIMED={len(claimed)} ORPHANS={orphans}')
        print()


if __name__ == '__main__':
    main()
