def f(data, sheet):
    """根因C变体：双层 for 内的三元实参（对应 creat_sheet2 的 i/j 循环嵌套）。"""
    for i in range(len(data)):
        for j in range(len(data[i])):
            t = data[i][j]
            sheet.write(i, 0, t['dt'])
            sheet.write(i, 2, t['symbol'])
            sheet.write(i, 3, '买' if t['amount'] > 0 else '卖')
            sheet.write(i, 4, abs(t['amount']))
            sheet.write(i, 5, float(t['price']))
