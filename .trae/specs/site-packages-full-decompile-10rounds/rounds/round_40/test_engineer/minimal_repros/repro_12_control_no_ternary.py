def f(data, sheet):
    """隔离对照：与 repro_11 相同但完全不含三元。

    用于判定 C 组丢失是否依赖三元本身；若本例 PASS 则触发条件需要
    三元 merge 块与循环回边块共享（IfExp 吞并域），若 FAIL 则是更一般
    的循环尾块 CALL 语句丢失。
    """
    for i in range(len(data)):
        t = data[i]
        if t[3] > 0:
            side = '买'
        else:
            side = '卖'
        sheet.write(i, 3, side)
        sheet.write(i, 4, abs(t[3]))
        sheet.write(i, 5, float(t[4]))
