def f(data, sheet):
    """对照用例：三元作为独立赋值语句（merge 块以 STORE 终结、无后续语句共享块）。

    已知良好形态（W40/R39 修复域），不应触发缺陷。
    """
    for i in range(len(data)):
        t = data[i]
        side = '买' if t[3] > 0 else '卖'
        sheet.write(i, 3, side)
        sheet.write(i, 4, abs(t[3]))
        sheet.write(i, 5, float(t[4]))
