def f(df, END):
    """根因B变体（对照）：同样 while(and) 复合条件但不在 try 内。

    验证 try 异常边混入 loop_successors（natural_exit 求解失败）是必要条件。
    """
    if df:
        df = list(df)
        while len(df) > 1 and df[-1] == END:
            df = df[:-1]
        out = df[-1]
        return out
    else:
        return 'missing'
