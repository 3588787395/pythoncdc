def f(data, sheet):
    """根因C核心形态：三元内嵌于方法调用实参，merge 块承载后续语句。

    对应 creat_sheet2 stock 分支 j 循环：sheet.write(row, 3, '买' if amount > 0 else '卖')
    的三元 merge 块（1914）还包含 CALL write 收尾与后续 4 条 write + row += 1，
    生成阶段 merge 块语句被吞（AST 中 IfExp 数量为 0）。
    """
    for i in range(len(data)):
        t = data[i]
        sheet.write(i, 0, t[0])
        sheet.write(i, 1, t[1])
        sheet.write(i, 2, t[2])
        sheet.write(i, 3, '买' if t[3] > 0 else '卖')
        sheet.write(i, 4, abs(t[3]))
        sheet.write(i, 5, float(t[4]))
        sheet.write(i, 6, float(t[4] * t[5]))
