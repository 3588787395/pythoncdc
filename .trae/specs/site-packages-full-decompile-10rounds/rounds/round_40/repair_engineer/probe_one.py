"""探针：反编译指定 repro 文件并输出源码。用法: python probe_one.py <path>"""
import importlib.util
import marshal
import os
import sys

sys.path.insert(0, r'F:/Downloads/pythoncdc-main')

from pycdc import decompile_pyc


def main():
    src_path = sys.argv[1]
    with open(src_path, 'r', encoding='utf-8') as f:
        src = f.read()
    code = compile(src, os.path.basename(src_path), 'exec')
    tmp = os.path.join(os.path.dirname(os.path.abspath(__file__)), '_probe_tmp.pyc')
    with open(tmp, 'wb') as f:
        f.write(importlib.util.MAGIC_NUMBER)
        f.write(b'\x00' * 12)
        marshal.dump(code, f)
    print(decompile_pyc(tmp))


if __name__ == '__main__':
    main()
