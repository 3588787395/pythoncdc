#!/usr/bin/env python3
"""R40: 打印目标函数的完整区域树（类型/入口/条件/then/else/merge/blocks）。"""
import marshal
import sys
import types

ROOT = r'F:/Downloads/pythoncdc-main'
sys.path.insert(0, ROOT)

from core.cfg import build_cfg, CFGRegionAnalyzer

PYC = r'F:/Downloads/pythoncdc-main/site-packages/IQCommon/util/backtest_info_utils.pyc'


def off(b):
    return b.start_offset if b is not None else None


def offs(bs):
    return sorted(off(b) for b in (bs or []))


def find_code(c, name):
    if c.co_name == name:
        return c
    for k in c.co_consts:
        if isinstance(k, types.CodeType):
            r = find_code(k, name)
            if r is not None:
                return r
    return None


ATTRS = ('entry_block', 'entry', 'condition_block', 'header_block',
         'back_edge_block', 'merge_block', 'exit_block')
LISTS = ('then_blocks', 'else_blocks', 'body_blocks', 'condition_chain_blocks',
         'handler_blocks')


def walk(regions, depth=0):
    for r in regions:
        pad = '  ' * depth
        head = f'{pad}{type(r).__name__}'
        rt = getattr(r, 'region_type', None)
        if rt is not None:
            head += f' type={rt}'
        print(head)
        for a in ATTRS:
            if hasattr(r, a):
                v = getattr(r, a)
                if v is not None:
                    print(f'{pad}  {a}={off(v)}')
        for a in LISTS:
            if hasattr(r, a):
                v = getattr(r, a)
                if v:
                    print(f'{pad}  {a}={offs(v)}')
        print(f'{pad}  blocks={offs(getattr(r, "blocks", None))}')
        walk(r.children or [], depth + 1)


def main():
    with open(PYC, 'rb') as f:
        module = marshal.loads(f.read()[16:])
    for name in sys.argv[1:] or ['add_end_flag']:
        code = find_code(module, name)
        cfg = build_cfg(code)
        analyzer = CFGRegionAnalyzer(cfg)
        analyzer.analyze()
        print('=' * 70)
        print(name, ' blocks=', sorted(cfg.blocks))
        walk(analyzer.regions)


if __name__ == '__main__':
    main()
