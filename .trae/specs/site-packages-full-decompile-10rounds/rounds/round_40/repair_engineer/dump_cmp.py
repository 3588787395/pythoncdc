#!/usr/bin/env python3
"""R40: 导出指定函数的原始字节码与反编译重编译后字节码，便于逐指令对照。

用法:
  D:/Python/python.exe .trae/specs/.../round_40/repair_engineer/dump_cmp.py <pyc> <ok_py> <func_name> [start] [end]
"""
import dis
import marshal
import sys
import types

ROOT = r'F:/Downloads/pythoncdc-main'
sys.path.insert(0, ROOT)


def find_code(code, name):
    if code.co_name == name:
        return code
    for c in code.co_consts:
        if isinstance(c, types.CodeType):
            r = find_code(c, name)
            if r is not None:
                return r
    return None


def load_pyc(path):
    with open(path, 'rb') as f:
        data = f.read()
    return marshal.loads(data[16:])


def listing(code, start=None, end=None):
    out = []
    for ins in dis.get_instructions(code):
        if start is not None and ins.offset < start:
            continue
        if end is not None and ins.offset >= end:
            continue
        out.append(f'{ins.offset:6d} {ins.opname:<32} {ins.argrepr}')
    return out


def main():
    pyc, okpy, name = sys.argv[1], sys.argv[2], sys.argv[3]
    start = int(sys.argv[4]) if len(sys.argv) > 4 else None
    end = int(sys.argv[5]) if len(sys.argv) > 5 else None

    orig = find_code(load_pyc(pyc), name)
    with open(okpy, encoding='utf-8') as f:
        src = f.read()
    dec = find_code(compile(src, '<decomp>', 'exec'), name)
    if orig is None or dec is None:
        print('NOT FOUND', name, orig is not None, dec is not None)
        return
    lo = listing(orig, start, end)
    ld = listing(dec)
    print(f'=== ORIG {name} instrs={len(list(dis.get_instructions(orig)))} '
          f'(window {start}-{end}: {len(lo)}) ===')
    print('\n'.join(lo))
    print(f'=== DECOMP {name} instrs={len(ld)} ===')
    print('\n'.join(ld))


if __name__ == '__main__':
    main()
