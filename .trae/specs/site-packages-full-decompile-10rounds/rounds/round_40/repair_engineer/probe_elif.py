#!/usr/bin/env python3
"""R40: 打印 add_end_flag 中 IF_ELIF_CHAIN(entry=6) 的 elif 结构细节 + CFG 前驱/后继。"""
import marshal
import sys
import types

ROOT = r'F:/Downloads/pythoncdc-main'
sys.path.insert(0, ROOT)

from core.cfg import build_cfg, CFGRegionAnalyzer
from core.cfg.region_analyzer import IfRegion

PYC = r'F:/Downloads/pythoncdc-main/site-packages/IQCommon/util/backtest_info_utils.pyc'


def off(b):
    return b.start_offset if b is not None else None


def offs(bs):
    return sorted(off(b) for b in (bs or []))


def find_code(c, name):
    if c.co_name == name:
        return c
    for k in c.co_consts:
        if isinstance(k, types.CodeType):
            r = find_code(k, name)
            if r is not None:
                return r
    return None


def dis(blk):
    out = []
    for i in blk.instructions:
        if i.opname in ('CACHE', 'EXTENDED_ARG'):
            continue
        out.append(f'{i.offset}:{i.opname}({i.argval})')
    return ' '.join(out)


def main():
    with open(PYC, 'rb') as f:
        module = marshal.loads(f.read()[16:])
    code = find_code(module, 'add_end_flag')
    cfg = build_cfg(code)
    a = CFGRegionAnalyzer(cfg)
    a.analyze()
    target = None

    def walk(rs):
        nonlocal target
        for r in rs:
            if isinstance(r, IfRegion) and off(getattr(r,'entry',None)) == 6:
                target = r
            walk(r.children or [])
    walk(a.regions)
    if target is None:
        print('not found')
        return
    print('IF_ELIF_CHAIN entry=', off(target.entry),
          'cond=', off(target.condition_block), 'merge=', off(target.merge_block))
    print(' then=', offs(target.then_blocks))
    print(' else=', offs(target.else_blocks))
    print(' elif_conditions=', offs(target.elif_conditions))
    for i, b in enumerate(target.elif_bodies or []):
        print(f' elif_bodies[{i}]=', offs(b))
    print(' elif_final_else=', offs(target.elif_final_else))
    print()
    print('--- CFG 关键块 ---')
    for bo in [6, 48, 56, 98, 100, 206, 210, 214]:
        blk = cfg.get_block_by_offset(bo)
        if blk is None:
            print(bo, 'MISSING')
            continue
        last = blk.get_last_instruction()
        print(f'@{bo} preds={sorted(p.start_offset for p in blk.predecessors)} '
              f'succs={sorted(s.start_offset for s in blk.successors)} '
              f'last={last.opname}({last.argval})')
        print('     ', dis(blk)[:200])


if __name__ == '__main__':
    main()
