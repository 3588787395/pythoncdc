#!/usr/bin/env python3
"""R40: 打印目标函数内 LoopRegion 的结构属性（header/condition/back_edge/chain/BoolOp）。"""
import marshal
import sys
import types

ROOT = r'F:/Downloads/pythoncdc-main'
sys.path.insert(0, ROOT)

from core.cfg import build_cfg, CFGRegionAnalyzer
from core.cfg.region_analyzer import LoopRegion, BoolOpRegion

PYC = r'F:/Downloads/pythoncdc-main/site-packages/IQCommon/util/backtest_info_utils.pyc'


def off(b):
    return b.start_offset if b is not None else None


def find_code(c, name):
    if c.co_name == name:
        return c
    for k in c.co_consts:
        if isinstance(k, types.CodeType):
            r = find_code(k, name)
            if r is not None:
                return r
    return None


def walk(regions, depth=0):
    for r in regions:
        if isinstance(r, LoopRegion):
            print('  ' * depth, f'LoopRegion type={r.region_type}')
            print('  ' * depth, f'  header={off(r.header_block)} condition={off(r.condition_block)} '
                                f'back_edge={off(r.back_edge_block)} exit={off(getattr(r, "exit_block", None))}')
            print('  ' * depth, f'  body={sorted(off(b) for b in r.body_blocks)} '
                                f'else={sorted(off(b) for b in (r.else_blocks or []))}')
            print('  ' * depth, f'  chain={sorted(off(b) for b in (r.condition_chain_blocks or []))} '
                                f'blocks={sorted(off(b) for b in (r.blocks or []))}')
            for ch in (r.children or []):
                if isinstance(ch, BoolOpRegion):
                    print('  ' * depth, f'  BoolOp merge={off(ch.merge_block)} '
                                        f'chain={[(off(cb), op) for cb, op in (ch.op_chain or [])]} '
                                        f'prefix={off(getattr(ch, "prefix_block", None))}')
        if r.children:
            walk(r.children, depth + 1)


def main():
    with open(PYC, 'rb') as f:
        module = marshal.loads(f.read()[16:])
    for name in sys.argv[1:] or ['backtest_download_result']:
        code = find_code(module, name)
        cfg = build_cfg(code)
        analyzer = CFGRegionAnalyzer(cfg)
        analyzer.analyze()
        print('=' * 70)
        print(name)
        walk(analyzer.regions)


if __name__ == '__main__':
    main()


