"""探针：输出编译后函数的 dis，按块划分。用法: python probe_dis.py <path>"""
import importlib.util
import dis
import marshal
import os
import sys


def main():
    src_path = sys.argv[1]
    with open(src_path, 'r', encoding='utf-8') as f:
        src = f.read()
    code = compile(src, os.path.basename(src_path), 'exec')
    for c in code.co_consts:
        if hasattr(c, 'co_code'):
            print('=' * 30, c.co_name)
            dis.dis(c)


if __name__ == '__main__':
    main()
