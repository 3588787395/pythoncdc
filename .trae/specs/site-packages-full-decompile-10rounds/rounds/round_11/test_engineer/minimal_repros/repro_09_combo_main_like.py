def run(cfg, pm):
    code = None
    ex = None
    try:
        helper = make()
        use(helper)
        work(cfg)
        if cfg.prof:
            profile(cfg)
    except ValueError as e1:
        ex = e1
        code = parse(e1)
    except Exception as e2:
        ex = e2
        code = parse_sys(cfg.path)
    else:
        code = 'OK'
        ex = None
    finally:
        if cfg.kind == 'BT' and cfg.log_enabled is False:
            with open('bt.log', 'a') as fa:
                fa.write('END.\\n')
        pm.publish(code=code)
        pm.release(code)
    return code
