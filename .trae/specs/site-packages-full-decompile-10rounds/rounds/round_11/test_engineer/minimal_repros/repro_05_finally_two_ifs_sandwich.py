# 缺陷家族与根因详见 ../decompile_report.md、../../repair_engineer/task_brief.md
def f(a, b):
    try:
        v = calc(a)
    except KeyError:
        v = 0
    except TypeError:
        v = -1
    finally:
        log(v)
        if a > b:
            mark('gt')
        total = v + a
        if b > 9:
            reset(b)
        done = True
    return v, total, done
