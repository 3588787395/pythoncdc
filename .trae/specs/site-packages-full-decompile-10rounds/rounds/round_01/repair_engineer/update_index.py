"""Update pyc_index.json: mark IQCommon/__init__.pyc as OK and generate OK.py file."""
import json, os, sys
sys.path.insert(0, 'f:/Downloads/pythoncdc-main')
os.chdir('f:/Downloads/pythoncdc-main')

# Load index
idx = json.load(open('pyc_index.json', 'r'))

# Find and update the entry
target = 'IQCommon/__init__.pyc'
updated = False
for entry in idx:
    if target in entry['path']:
        entry['decompile_status'] = 'ok'
        entry['bytecode_match_rate'] = 1.0
        entry['ok_py_generated'] = True
        entry['last_tested_round'] = 1
        updated = True
        print(f"Updated: {entry['path']} -> ok")
        break

if not updated:
    print("ERROR: entry not found!")
    sys.exit(1)

# Save index
with open('pyc_index.json', 'w') as f:
    json.dump(idx, f, indent=2, ensure_ascii=False)
print("pyc_index.json updated")

# Generate OK.py file
ok_path = 'site-packages/IQCommon/__init__OK.py'
from pycdc import decompile_pyc
source = decompile_pyc('site-packages/IQCommon/__init__.pyc')
with open(ok_path, 'w', encoding='utf-8') as f:
    f.write(source)
print(f"OK.py generated: {ok_path}")

# Verify it compiles
with open(ok_path, 'r', encoding='utf-8') as f:
    content = f.read()
# Strip header
lines = content.split('\n')
while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
    lines.pop(0)
source = '\n'.join(lines)
compile(source, '<test>', 'exec')
print("OK.py compiles successfully!")

# Count totals
ok_count = sum(1 for e in idx if e['decompile_status'] == 'ok')
partial_count = sum(1 for e in idx if e['decompile_status'] == 'partial')
print(f"\nTotal: {len(idx)}, OK: {ok_count}, Partial: {partial_count}")
print(f"OK rate: {ok_count/len(idx)*100:.1f}%")
