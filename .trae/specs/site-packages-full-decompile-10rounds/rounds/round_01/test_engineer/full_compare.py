import dis, marshal, struct, types, io

def load_code_from_pyc(pyc_path):
    f = open(pyc_path, 'rb')
    f.read(16)
    code = marshal.load(f)
    return code

def get_func_code(code_obj):
    for c in code_obj.co_consts:
        if hasattr(c, 'co_code'):
            return c
    return None

# Load original
code = load_code_from_pyc('site-packages/IQCommon/__init__.pyc')

# Check all functions including module
print("=== MODULE-LEVEL CHECK ===")
# Compare module-level bytecode
decompiled_src = open('.trae/specs/site-packages-full-decompile-10rounds/rounds/round_01/test_engineer/decompiled.py', 'r', encoding='utf-16').read()
if decompiled_src and decompiled_src[0] == '\ufeff':
    decompiled_src = decompiled_src[1:]

# Strip header
lines = decompiled_src.split('\n')
while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
    lines.pop(0)
decompiled_src = '\n'.join(lines)

decomp_code = compile(decompiled_src, '<decompiled>', 'exec')

# Compare module-level code
orig_instrs = list(dis.get_instructions(code))
decomp_instrs = list(dis.get_instructions(decomp_code))
print(f"Module: orig={len(orig_instrs)} instrs, decomp={len(decomp_instrs)} instrs")
mismatches = 0
for i in range(max(len(orig_instrs), len(decomp_instrs))):
    o = orig_instrs[i] if i < len(orig_instrs) else None
    d = decomp_instrs[i] if i < len(decomp_instrs) else None
    if o is None or d is None:
        mismatches += 1
        continue
    if o.opname != d.opname or o.arg != d.arg:
        mismatches += 1
        if mismatches <= 10:
            print(f"  MISMATCH [{i}]: orig={o.opname} {o.argrepr} vs decomp={d.opname} {d.argrepr}")
print(f"Module mismatches: {mismatches}")

# Compare each function
print("\n=== FUNCTION-LEVEL CHECK ===")
fn_orig = get_func_code(code)
fn_decomp = get_func_code(decomp_code)
if fn_orig and fn_decomp:
    orig_instrs = list(dis.get_instructions(fn_orig))
    decomp_instrs = list(dis.get_instructions(fn_decomp))
    print(f"{fn_orig.co_name}: orig={len(orig_instrs)} instrs, decomp={len(decomp_instrs)} instrs")
    mismatches = 0
    for i in range(max(len(orig_instrs), len(decomp_instrs))):
        o = orig_instrs[i] if i < len(orig_instrs) else None
        d = decomp_instrs[i] if i < len(decomp_instrs) else None
        if o is None or d is None:
            mismatches += 1
            continue
        if o.opname != d.opname or o.arg != d.arg:
            mismatches += 1
            if mismatches <= 10:
                print(f"  MISMATCH [{i}]: orig={o.opname} {o.argrepr} vs decomp={d.opname} {d.argrepr}")
    print(f"{fn_orig.co_name} mismatches: {mismatches}")

# Also compare raw bytecode bytes
print("\n=== RAW BYTECODE COMPARISON ===")
print(f"Module co_code match: {code.co_code == decomp_code.co_code}")
if fn_orig and fn_decomp:
    print(f"Function co_code match: {fn_orig.co_code == fn_decomp.co_code}")
    print(f"Exception table match: {fn_orig.co_exceptiontable == fn_decomp.co_exceptiontable}")

print("\n=== VERDICT ===")
if code.co_code == decomp_code.co_code and (not fn_orig or fn_orig.co_code == fn_decomp.co_code):
    print("FULL MATCH - bytecode is identical!")
else:
    print("MISMATCH detected")
