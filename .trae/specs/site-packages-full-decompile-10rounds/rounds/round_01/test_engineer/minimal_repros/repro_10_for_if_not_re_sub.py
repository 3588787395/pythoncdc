import re
def test(d, content):
    result = []
    for k, v in d.items():
        if not k < 'm':
            pattern = '(?<![.\w])\s*' + re.escape(k) + '\('
            matches = re.findall(pattern, content)
            if len(matches) > 0 and k not in result:
                result.append(k)
    return result
