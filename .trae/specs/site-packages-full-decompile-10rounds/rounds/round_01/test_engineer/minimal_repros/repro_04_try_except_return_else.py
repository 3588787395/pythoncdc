"""Minimal repro: try-except with bare except + return in try body.
This mirrors the get_python_version function pattern exactly.
"""
import sys
import traceback

def get_python_version():
    import traceback
    import sys
    flag = '0'
    try:
        if sys.version_info[0] == 3 and sys.version_info[1] == 11:
            flag = '3.11'
        else:
            print('error')
    except:
        traceback.print_exc()
    try:
        globals()['python_version'] = flag
    except:
        globals()['python_version'] = flag
    return flag
