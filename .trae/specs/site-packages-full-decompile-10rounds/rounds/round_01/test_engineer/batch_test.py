"""Batch test all partial pyc files and report which ones actually pass/fail."""
import json, os, sys, subprocess, dis, marshal, types, io, traceback

def load_code_from_pyc(pyc_path):
    f = open(pyc_path, 'rb')
    f.read(16)
    code = marshal.load(f)
    return code

def get_all_code_objects(code_obj, prefix=''):
    """Recursively get all code objects from a module."""
    result = {}
    name = prefix + code_obj.co_name if prefix else '<module>'
    result[name] = code_obj
    for const in code_obj.co_consts:
        if hasattr(const, 'co_code'):
            child_name = f"{name}.{const.co_name}" if name != '<module>' else const.co_name
            result.update(get_all_code_objects(const, child_name + '.'))
    return result

def compile_decompiled(py_path):
    """Compile the decompiled python file and return the code object."""
    # Try different encodings
    for enc in ['utf-8', 'utf-16', 'utf-16-le', 'gbk', 'latin-1']:
        try:
            src = open(py_path, 'r', encoding=enc).read()
            if src and src[0] == '\ufeff':
                src = src[1:]
            return compile(src, py_path, 'exec')
        except (UnicodeDecodeError, SyntaxError):
            continue
    return None

def compare_bytecode_bytes(orig_code, decomp_code):
    """Compare raw bytecode bytes of two code objects."""
    if orig_code.co_code != decomp_code.co_code:
        return False
    if orig_code.co_exceptiontable != decomp_code.co_exceptiontable:
        return False
    return True

def test_pyc(pyc_path):
    """Test if a pyc file decompiles correctly."""
    # Step 1: Decompile
    result = subprocess.run(
        [sys.executable, 'pycdc.py', pyc_path],
        capture_output=True, text=True, timeout=60,
        cwd='f:/Downloads/pythoncdc-main'
    )
    if result.returncode != 0:
        return False, f"decompile failed: {result.stderr[:200]}"
    
    # Step 2: Save output and compile
    decompiled_path = pyc_path.replace('.pyc', '_decompiled_test.py')
    with open(decompiled_path, 'wb') as f:
        f.write(result.stdout.encode('utf-16'))
    
    # Also try utf-8
    with open(decompiled_path, 'w', encoding='utf-8') as f:
        f.write(result.stdout)
    
    try:
        decomp_code = compile(result.stdout, '<decompiled>', 'exec')
    except SyntaxError as e:
        try:
            os.remove(decompiled_path)
        except:
            pass
        return False, f"compile failed: {e}"
    
    # Step 3: Load original
    try:
        orig_code = load_code_from_pyc(pyc_path)
    except Exception as e:
        try:
            os.remove(decompiled_path)
        except:
            pass
        return False, f"load failed: {e}"
    
    # Step 4: Compare module-level bytecode
    if not compare_bytecode_bytes(orig_code, decomp_code):
        try:
            os.remove(decompiled_path)
        except:
            pass
        return False, "module bytecode mismatch"
    
    # Step 5: Compare all function code objects
    orig_funcs = {}
    for const in orig_code.co_consts:
        if hasattr(const, 'co_code'):
            orig_funcs[const.co_name] = const
    
    decomp_funcs = {}
    for const in decomp_code.co_consts:
        if hasattr(const, 'co_code'):
            decomp_funcs[const.co_name] = const
    
    matched = 0
    total = len(orig_funcs)
    mismatches = []
    for name, orig_fn in orig_funcs.items():
        if name in decomp_funcs:
            if compare_bytecode_bytes(orig_fn, decomp_funcs[name]):
                matched += 1
            else:
                mismatches.append(name)
        else:
            mismatches.append(f"{name} (missing)")
    
    try:
        os.remove(decompiled_path)
    except:
        pass
    
    if matched == total:
        return True, f"all {total} functions match"
    else:
        return False, f"{matched}/{total} matched, mismatches: {mismatches[:5]}"

# Load index
idx = json.load(open('pyc_index.json', 'r'))
partial_files = [e for e in idx if e['decompile_status'] == 'partial']

print(f"Testing {len(partial_files)} partial files...")
print()

passed = []
failed = []

for i, entry in enumerate(partial_files):
    pyc_path = entry['path']
    if not os.path.exists(pyc_path):
        continue
    
    try:
        ok, msg = test_pyc(pyc_path)
    except Exception as e:
        ok, msg = False, f"exception: {e}"
    
    status = "OK" if ok else "FAIL"
    fn_count = entry.get('function_count', '?')
    match_rate = entry.get('bytecode_match_rate', '?')
    print(f"[{i+1}/{len(partial_files)}] {status} {pyc_path} (fn={fn_count}, match={match_rate}): {msg}")
    
    if ok:
        passed.append(entry)
    else:
        failed.append(entry)

print(f"\n=== SUMMARY ===")
print(f"Passed (actually OK): {len(passed)}")
print(f"Failed (truly partial): {len(failed)}")
print(f"\nPassed files:")
for e in passed:
    print(f"  {e['path']}")
print(f"\nFirst 20 failed files:")
for e in failed[:20]:
    print(f"  {e['path']} (fn={e.get('function_count','?')}, match={e.get('bytecode_match_rate','?')})")
