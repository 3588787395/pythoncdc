"""Test a single pyc file for bytecode match."""
import sys, os, dis, marshal, subprocess

def load_code_from_pyc(pyc_path):
    with open(pyc_path, 'rb') as f:
        f.read(16)
        code = marshal.load(f)
    return code

def compare_code_objects(orig_code, decomp_code):
    if orig_code.co_code != decomp_code.co_code:
        return False, "code mismatch"
    if orig_code.co_exceptiontable != decomp_code.co_exceptiontable:
        return False, "exception table mismatch"
    
    orig_funcs = [c for c in orig_code.co_consts if hasattr(c, 'co_code')]
    decomp_funcs = [c for c in decomp_code.co_consts if hasattr(c, 'co_code')]
    
    if len(orig_funcs) != len(decomp_funcs):
        return False, f"function count: {len(orig_funcs)} vs {len(decomp_funcs)}"
    
    for of, df in zip(orig_funcs, decomp_funcs):
        ok, msg = compare_code_objects(of, df)
        if not ok:
            return False, f"{of.co_name}: {msg}"
    
    return True, "match"

pyc_path = sys.argv[1] if len(sys.argv) > 1 else 'site-packages/IQData/api/get_block_stocks.pyc'

result = subprocess.run(
    [sys.executable, 'pycdc.py', pyc_path],
    capture_output=True, timeout=60,
    cwd='f:/Downloads/pythoncdc-main'
)
stdout = result.stdout.decode('utf-8', errors='replace')
stderr = result.stderr.decode('utf-8', errors='replace') if result.stderr else ''

print(f"=== Decompiling: {pyc_path} ===")
print(f"Return code: {result.returncode}")
if stderr:
    print(f"Stderr: {stderr[:500]}")

try:
    decomp_code = compile(stdout, '<decompiled>', 'exec')
except SyntaxError as e:
    print(f"COMPILE ERROR: {e}")
    sys.exit(1)

orig_code = load_code_from_pyc(pyc_path)
ok, msg = compare_code_objects(orig_code, decomp_code)

if ok:
    print(f"RESULT: FULL MATCH")
else:
    print(f"RESULT: MISMATCH - {msg}")
    
    # Show details for functions
    orig_funcs = {c.co_name: c for c in orig_code.co_consts if hasattr(c, 'co_code')}
    decomp_funcs = {c.co_name: c for c in decomp_code.co_consts if hasattr(c, 'co_code')}
    
    for name, of in orig_funcs.items():
        if name in decomp_funcs:
            df = decomp_funcs[name]
            if of.co_code != df.co_code:
                print(f"\n  Function: {name}")
                print(f"  Original: {len(of.co_code)} bytes")
                print(f"  Decompiled: {len(df.co_code)} bytes")
                
                # Show instruction diff
                orig_instrs = list(dis.get_instructions(of))
                decomp_instrs = list(dis.get_instructions(df))
                print(f"  Original instructions: {len(orig_instrs)}")
                print(f"  Decompiled instructions: {len(decomp_instrs)}")
                
                # Show first mismatch
                for i in range(max(len(orig_instrs), len(decomp_instrs))):
                    o = orig_instrs[i] if i < len(orig_instrs) else None
                    d = decomp_instrs[i] if i < len(decomp_instrs) else None
                    if o is None:
                        print(f"  Extra in decompiled [{i}]: {d.opname} {d.argrepr}")
                        break
                    if d is None:
                        print(f"  Missing in decompiled [{i}]: {o.opname} {o.argrepr}")
                        break
                    if o.opname != d.opname or o.arg != d.arg:
                        print(f"  First mismatch [{i}]:")
                        print(f"    Original:   {o.offset:4d} {o.opname:30s} {o.argrepr}")
                        print(f"    Decompiled: {d.offset:4d} {d.opname:30s} {d.argrepr}")
                        break
        else:
            print(f"\n  Missing function: {name}")
