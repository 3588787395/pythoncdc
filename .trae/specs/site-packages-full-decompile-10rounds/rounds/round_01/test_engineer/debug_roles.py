"""Debug: Check what block roles are assigned to the check_strategy function."""
import sys, os, dis, marshal
sys.path.insert(0, 'f:/Downloads/pythoncdc-main')
os.chdir('f:/Downloads/pythoncdc-main')

from core.cfg import build_cfg
from core.cfg.region_analyzer import RegionAnalyzer, BlockRole

# Load
with open('site-packages/IQCommon/api/check_strategy.pyc', 'rb') as f:
    f.read(16)
    code = marshal.load(f)

fn = [c for c in code.co_consts if hasattr(c, 'co_code')][0]

# Build CFG
cfg = build_cfg(fn)

# Analyze regions
analyzer = RegionAnalyzer(cfg, fn)
regions = analyzer.analyze()

# Print block roles for relevant offsets
print("=== BLOCK ROLES ===")
for offset in sorted(analyzer.block_roles.keys()):
    role = analyzer.block_roles[offset]
    if role != BlockRole.NORMAL:
        block = cfg.get_block_by_offset(offset)
        if block:
            instrs = [i.opname for i in block.instructions]
            print(f"  offset={offset:4d} role={role.name:20s} instrs={instrs[:5]}")

# Print loop regions
print("\n=== LOOP REGIONS ===")
from core.cfg.region_analyzer import LoopRegion
for r in regions:
    if isinstance(r, LoopRegion):
        print(f"  Loop at header={r.header_block.start_offset if r.header_block else None}")
        print(f"    body_blocks: {[b.start_offset for b in r.body_blocks]}")
        print(f"    back_edge: {r.back_edge_block.start_offset if r.back_edge_block else None}")
        if hasattr(r, 'continue_map'):
            print(f"    continue_map: {dict((k.start_offset, v) for k, v in r.continue_map.items())}")

# Print IfRegions
print("\n=== IF REGIONS ===")
from core.cfg.region_analyzer import IfRegion
for r in regions:
    if isinstance(r, IfRegion):
        print(f"  If at entry={r.entry.start_offset if r.entry else None}")
        print(f"    then_blocks: {[b.start_offset for b in r.then_blocks]}")
        print(f"    else_blocks: {[b.start_offset for b in r.else_blocks]}")
        if r.merge_block:
            print(f"    merge: {r.merge_block.start_offset}")
