import dis, marshal, sys
sys.path.insert(0, 'f:/Downloads/pythoncdc-main')
import os; os.chdir('f:/Downloads/pythoncdc-main')

from pycdc import decompile_pyc

# Load original
with open('site-packages/IQCommon/api/check_strategy.pyc', 'rb') as f:
    f.read(16)
    code = marshal.load(f)
fn = [c for c in code.co_consts if hasattr(c, 'co_code')][0]

# Decompile
source = decompile_pyc('site-packages/IQCommon/api/check_strategy.pyc')
# Strip header
lines = source.split('\n')
while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
    lines.pop(0)
source = '\n'.join(lines)
decomp_code = compile(source, '<decompiled>', 'exec')
decomp_fn = [c for c in decomp_code.co_consts if hasattr(c, 'co_code')][0]

# Compare instruction by instruction
orig_instrs = list(dis.get_instructions(fn))
decomp_instrs = list(dis.get_instructions(decomp_fn))

print(f"Original: {len(orig_instrs)} instructions")
print(f"Decompiled: {len(decomp_instrs)} instructions")
print()

# Find all mismatches
max_len = max(len(orig_instrs), len(decomp_instrs))
for i in range(max_len):
    o = orig_instrs[i] if i < len(orig_instrs) else None
    d = decomp_instrs[i] if i < len(decomp_instrs) else None
    if o is None:
        print(f"[{i:3d}] EXTRA in decompiled: {d.opname} {d.argrepr}")
        continue
    if d is None:
        print(f"[{i:3d}] MISSING in decompiled: {o.opname} {o.argrepr}")
        continue
    if o.opname != d.opname or o.arg != d.arg:
        print(f"[{i:3d}] MISMATCH:")
        print(f"  ORIG: {o.offset:4d} {o.opname:30s} {o.argrepr}")
        print(f"  DECP: {d.offset:4d} {d.opname:30s} {d.argrepr}")

# Show context around the first mismatch
print("\n=== Context around first mismatch (instr 28) ===")
for i in range(20, 40):
    o = orig_instrs[i] if i < len(orig_instrs) else None
    d = decomp_instrs[i] if i < len(decomp_instrs) else None
    if o:
        print(f"  [{i:3d}] ORIG: {o.offset:4d} {o.opname:30s} {o.argrepr}")
    if d:
        print(f"  [{i:3d}] DECP: {d.offset:4d} {d.opname:30s} {d.argrepr}")
    print()
