import dis, marshal, sys, os
sys.path.insert(0, 'f:/Downloads/pythoncdc-main')
os.chdir('f:/Downloads/pythoncdc-main')
from pycdc import decompile_pyc

# Load original
py_path = '.trae/specs/site-packages-full-decompile-10rounds/rounds/round_01/test_engineer/minimal_repros/repro_05_if_not_comparison_chain.py'
with open(py_path, 'r', encoding='utf-8') as f:
    source = f.read()
orig_code = compile(source, py_path, 'exec')

# Save pyc
pyc_path = py_path.replace('.py', '.pyc')
with open(pyc_path, 'wb') as f:
    f.write(b'\x6f\x0d\x0d\x0a\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00')
    marshal.dump(orig_code, f)

# Decompile
decomp_source = decompile_pyc(pyc_path)
lines = decomp_source.split('\n')
while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
    lines.pop(0)
decomp_source = '\n'.join(lines)
print("=== DECOMPILED SOURCE ===")
print(decomp_source)
print()

# Compile decompiled
decomp_code = compile(decomp_source, '<decompiled>', 'exec')

# Get function code objects
orig_fn = [c for c in orig_code.co_consts if hasattr(c, 'co_code')][0]
decomp_fn = [c for c in decomp_code.co_consts if hasattr(c, 'co_code')][0]

print("=== ORIGINAL DISASSEMBLY ===")
dis.dis(orig_fn)
print("\n=== DECOMPILED DISASSEMBLY ===")
dis.dis(decomp_fn)
