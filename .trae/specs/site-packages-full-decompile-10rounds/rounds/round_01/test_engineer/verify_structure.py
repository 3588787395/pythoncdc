import dis, marshal, struct

# Load original
f = open('site-packages/IQCommon/__init__.pyc', 'rb')
f.read(16)
code = marshal.load(f)
fn = [c for c in code.co_consts if hasattr(c, 'co_code')][0]

print("=== ORIGINAL EXCEPTION TABLE (via dis._parse_exception_table) ===")
for entry in dis._parse_exception_table(fn):
    print(f"  {entry.start} to {entry.end} -> {entry.target} [depth={entry.depth}]" + (" lasti" if entry.lasti else ""))

print("\n=== ORIGINAL DISASSEMBLY (offsets >= 400) ===")
for instr in dis.get_instructions(fn):
    if instr.offset >= 400:
        print(f"  {instr.offset:4d} {instr.opname:30s} {instr.argrepr}")

