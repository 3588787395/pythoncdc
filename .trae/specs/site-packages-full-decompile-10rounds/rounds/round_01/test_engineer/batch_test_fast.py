def load_code_from_pyc(pyc_path):
    with open(pyc_path, 'rb') as f:
        f.read(16)
        code = marshal.load(f)
    return code

def compare_code_objects(orig_code, decomp_code):
    if orig_code.co_code != decomp_code.co_code:
        return False, "code mismatch"
    if orig_code.co_exceptiontable != decomp_code.co_exceptiontable:
        return False, "exception table mismatch"
    orig_funcs = [c for c in orig_code.co_consts if hasattr(c, 'co_code')]
    decomp_funcs = [c for c in decomp_code.co_consts if hasattr(c, 'co_code')]
    if len(orig_funcs) != len(decomp_funcs):
        return False, f"func count {len(orig_funcs)} vs {len(decomp_funcs)}"
    for of, df in zip(orig_funcs, decomp_funcs):
        ok, msg = compare_code_objects(of, df)
        if not ok:
            return False, f"{of.co_name}: {msg}"
    return True, "match"

from pycdc import decompile_pyc

def test_pyc(pyc_path):
    try:
        source = decompile_pyc(pyc_path)
        if source is None:
            return False, "no output"
        # Strip header
        lines = source.split('\n')
        while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
            lines.pop(0)
        source = '\n'.join(lines)
        decomp_code = compile(source, '<decompiled>', 'exec')
        orig_code = load_code_from_pyc(pyc_path)
        ok, msg = compare_code_objects(orig_code, decomp_code)
        return ok, msg, source
    except SyntaxError as e:
        return False, f"SyntaxError: {e}", None
    except Exception as e:
        return False, f"Exception: {str(e)[:100]}", None

idx = json.load(open('pyc_index.json', 'r'))
partial_files = [e for e in idx if e['decompile_status'] == 'partial']

print(f"Testing {len(partial_files)} partial files...", flush=True)

passed = []
failed = []

for i, entry in enumerate(partial_files):
    pyc_path = entry['path'].replace('\\', '/')
    if not os.path.exists(pyc_path):
        continue
    
    try:
        ok, msg, source = test_pyc(pyc_path)
    except Exception as e:
        ok, msg, source = False, f"outer exception: {str(e)[:80]}", None
    
    status = "OK" if ok else "FAIL"
    fn_count = entry.get('function_count', '?')
    
    if ok:
        print(f"[{i+1}/{len(partial_files)}] OK {pyc_path} (fn={fn_count})", flush=True)
        passed.append(entry)
    else:
        if i < 10 or i % 30 == 0:
            print(f"[{i+1}/{len(partial_files)}] FAIL {pyc_path} (fn={fn_count}): {msg[:80]}", flush=True)
        failed.append(entry)

print(f"\n=== SUMMARY ===", flush=True)
print(f"Passed (actually OK): {len(passed)}", flush=True)
print(f"Failed (truly partial): {len(failed)}", flush=True)
print(f"\nPassed files:", flush=True)
for e in passed:
    print(f"  {e['path']}", flush=True)
print(f"\nFirst 30 failed files (sorted by function_count):", flush=True)
failed_sorted = sorted(failed, key=lambda e: e.get('function_count', 999))
for e in failed_sorted[:30]:
    print(f"  {e['path']} (fn={e.get('function_count','?')}, match={e.get('bytecode_match_rate','?')})", flush=True)
