# Use subprocess but with encoding fix
import subprocess

def decompile_via_subprocess(pyc_path):
    result = subprocess.run(
        [sys.executable, 'pycdc.py', pyc_path],
        capture_output=True, timeout=60,
        cwd='f:/Downloads/pythoncdc-main'
    )
    # Decode as utf-8 with errors='replace'
    stdout = result.stdout.decode('utf-8', errors='replace')
    stderr = result.stderr.decode('utf-8', errors='replace') if result.stderr else ''
    return stdout, stderr, result.returncode

def test_pyc(pyc_path):
    """Test if a pyc file decompiles correctly."""
    stdout, stderr, rc = decompile_via_subprocess(pyc_path)
    if rc != 0:
        return False, f"decompile rc={rc}: {stderr[:200]}"
    
    # Compile decompiled source
    try:
        decomp_code = compile(stdout, '<decompiled>', 'exec')
    except SyntaxError as e:
        return False, f"compile error: {e}"
    
    # Load original
    try:
        orig_code = load_code_from_pyc(pyc_path)
    except Exception as e:
        return False, f"load failed: {e}"
    
    # Compare
    ok, msg = compare_code_objects(orig_code, decomp_code)
    return ok, msg

