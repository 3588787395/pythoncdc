def load_code_from_pyc(pyc_path):
    with open(pyc_path, 'rb') as f:
        f.read(16)
        code = marshal.load(f)
    return code

def compare_code_objects(orig_code, decomp_code):
    """Compare raw bytecode of two code objects recursively."""
    if orig_code.co_code != decomp_code.co_code:
        return False, "code mismatch"
    if orig_code.co_exceptiontable != decomp_code.co_exceptiontable:
        return False, "exception table mismatch"
    
    # Compare nested code objects
    orig_funcs = [c for c in orig_code.co_consts if hasattr(c, 'co_code')]
    decomp_funcs = [c for c in decomp_code.co_consts if hasattr(c, 'co_code')]
    
    if len(orig_funcs) != len(decomp_funcs):
        return False, f"function count: {len(orig_funcs)} vs {len(decomp_funcs)}"
    
    for of, df in zip(orig_funcs, decomp_funcs):
        ok, msg = compare_code_objects(of, df)
        if not ok:
            return False, f"{of.co_name}: {msg}"
    
    return True, "match"

def decompile_pyc(pyc_path):
    """Decompile a pyc file using the decompiler module directly."""
    try:
        from core.pyc_loader_v2 import load_pyc_file
        from core.cfg.cfg_builder import CFGBuilder
        from core.cfg.region_analyzer import RegionAnalyzer
        from core.cfg.region_ast_generator import RegionASTGenerator
        
        # Load
        loader = load_pyc_file(pyc_path)
        code_obj = loader.code_object
        
        # Build CFG
        cfg_builder = CFGBuilder()
        cfg = cfg_builder.build(code_obj)
        
        # Analyze regions
        analyzer = RegionAnalyzer(cfg, code_obj)
        regions = analyzer.analyze()
        
        # Generate AST
        generator = RegionASTGenerator(cfg, code_obj, analyzer)
        ast_result = generator.generate(regions)
        
        # Convert to source
        import ast
        if isinstance(ast_result, dict):
            # Convert dict-based AST to source
            source = generator.dict_to_source(ast_result)
        else:
            source = ast.unparse(ast_result)
        
        return source, None
    except Exception as e:
        return None, traceback.format_exc()

