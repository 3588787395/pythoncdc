from pycdc import decompile_pyc
from core.cfg.cfg_builder import CFGBuilder
from core.cfg.region_analyzer import RegionAnalyzer

def load_code_from_pyc(pyc_path):
    with open(pyc_path, 'rb') as f:
        f.read(16)
        code = marshal.load(f)
    return code

def analyze_case(py_path, name):
    print(f"\n{'='*60}")
    print(f"Analyzing: {name}")
    print(f"{'='*60}")
    
    with open(py_path, 'r', encoding='utf-8') as f:
        source = f.read()
    
    code = compile(source, py_path, 'exec')
    
    test_func = None
    for c in code.co_consts:
        if hasattr(c, 'co_code') and c.co_name == 'test':
            test_func = c
            break
    
    if not test_func:
        print("  No test function found")
        return
    
    print("\n--- Original bytecode ---")
    for instr in dis.get_instructions(test_func):
        print(f"  {instr.offset:4d} {instr.opname} {instr.argrepr}")
    
    # Build CFG and analyze regions
    builder = CFGBuilder()
    cfg = builder.build(test_func)
    
    analyzer = RegionAnalyzer(cfg)
    analyzer.analyze()
    
    print(f"\n--- Regions ({len(analyzer.regions)}) ---")
    for r in analyzer.regions:
        rtype = type(r).__name__
        entry = r.entry.start_offset if r.entry else None
        print(f"  {rtype}: entry={entry}")
        if hasattr(r, 'then_blocks'):
            print(f"    then={[b.start_offset for b in r.then_blocks]}")
            print(f"    else={[b.start_offset for b in r.else_blocks] if r.else_blocks else None}")
            print(f"    merge={r.merge_block.start_offset if r.merge_block else None}")
            print(f"    cond={r.condition_block.start_offset if r.condition_block else None}")
        if hasattr(r, 'header_block'):
            print(f"    header={r.header_block.start_offset if r.header_block else None}")
            print(f"    body={[b.start_offset for b in r.body_blocks]}")
            print(f"    back_edge={r.back_edge_block.start_offset if r.back_edge_block else None}")
            print(f"    else={[b.start_offset for b in r.else_blocks] if r.else_blocks else None}")
    
    # Decompile
    pyc_path = py_path.replace('.py', '.pyc')
    with open(pyc_path, 'wb') as f:
        f.write(b'\x6f\x0d\x0d\x0a')
        f.write(b'\x00\x00\x00\x00')
        f.write(b'\x00\x00\x00\x00')
        f.write(b'\x00\x00\x00\x00')
        marshal.dump(code, f)
    
    decomp_source = decompile_pyc(pyc_path)
    lines = decomp_source.split('\n')
    while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
        lines.pop(0)
    decomp_source = '\n'.join(lines)
    
    print(f"\n--- Decompiled source ---")
    print(decomp_source)
    
    decomp_code = compile(decomp_source, '<decompiled>', 'exec')
    decomp_func = None
    for c in decomp_code.co_consts:
        if hasattr(c, 'co_code') and c.co_name == 'test':
            decomp_func = c
            break
    
    if decomp_func:
        print(f"\n--- Decompiled bytecode ---")
        for instr in dis.get_instructions(decomp_func):
            print(f"  {instr.offset:4d} {instr.opname} {instr.argrepr}")

repro_dir = '.trae/specs/site-packages-full-decompile-10rounds/rounds/round_01/test_engineer/minimal_repros'

for name in ['repro_02_if_not_for_else.py', 'repro_05_if_not_comparison_chain.py', 'repro_12_if_not_for_append.py']:
    py_path = os.path.join(repro_dir, name)
    analyze_case(py_path, name)
