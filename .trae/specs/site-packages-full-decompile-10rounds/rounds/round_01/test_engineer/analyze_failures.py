"""Analyze the 5 failing repro cases - show full bytecode comparison."""
import os, sys, dis, marshal, types

sys.path.insert(0, 'f:/Downloads/pythoncdc-main')
os.chdir('f:/Downloads/pythoncdc-main')
from pycdc import decompile_pyc

def load_code_from_pyc(pyc_path):
    with open(pyc_path, 'rb') as f:
        f.read(16)
        code = marshal.load(f)
    return code

def show_diff(orig_code, decomp_code, name=""):
    orig_instrs = list(dis.get_instructions(orig_code))
    decomp_instrs = list(dis.get_instructions(decomp_code))
    
    print(f"\n--- {name} (orig={len(orig_instrs)}, decomp={len(decomp_instrs)}) ---")
    
    max_len = max(len(orig_instrs), len(decomp_instrs))
    first_diff = -1
    for i in range(max_len):
        o = orig_instrs[i] if i < len(orig_instrs) else None
        d = decomp_instrs[i] if i < len(decomp_instrs) else None
        if o is None:
            print(f"  [{i}] EXTRA DECP: {d.opname} {d.argrepr}")
            if first_diff < 0: first_diff = i
            break
        if d is None:
            print(f"  [{i}] MISSING ORIG: {o.opname} {o.argrepr}")
            if first_diff < 0: first_diff = i
            break
        if o.opname != d.opname or o.arg != d.arg:
            print(f"  [{i}] ORIG: {o.offset:4d} {o.opname} {o.argrepr}")
            print(f"  [{i}] DECP: {d.offset:4d} {d.opname} {d.argrepr}")
            if first_diff < 0: first_diff = i
    
    if first_diff >= 0:
        # Show context around first diff
        start = max(0, first_diff - 3)
        end = min(max_len, first_diff + 10)
        print(f"  Context (instr {start}-{end}):")
        for i in range(start, end):
            o = orig_instrs[i] if i < len(orig_instrs) else None
            d = decomp_instrs[i] if i < len(decomp_instrs) else None
            o_str = f"{o.offset:4d} {o.opname} {o.argrepr}" if o else "---"
            d_str = f"{d.offset:4d} {d.opname} {d.argrepr}" if d else "---"
            match = "OK" if (o and d and o.opname == d.opname and o.arg == d.arg) else "XX"
            print(f"    [{i}] {match} ORIG: {o_str:40s} DECP: {d_str}")

repro_dir = '.trae/specs/site-packages-full-decompile-10rounds/rounds/round_01/test_engineer/minimal_repros'
failures = [
    'repro_02_if_not_for_else.py',
    'repro_05_if_not_comparison_chain.py', 
    'repro_06_for_if_not_method.py',
    'repro_10_for_if_not_re_sub.py',
    'repro_12_if_not_for_append.py',
]

for filename in failures:
    py_path = os.path.join(repro_dir, filename)
    with open(py_path, 'r', encoding='utf-8') as f:
        source = f.read()
    
    code = compile(source, py_path, 'exec')
    pyc_path = py_path.replace('.py', '.pyc')
    with open(pyc_path, 'wb') as f:
        f.write(b'\x6f\x0d\x0d\x0a')
        f.write(b'\x00\x00\x00\x00')
        f.write(b'\x00\x00\x00\x00')
        f.write(b'\x00\x00\x00\x00')
        marshal.dump(code, f)
    
    try:
        decomp_source = decompile_pyc(pyc_path)
    except Exception as e:
        print(f"\n[FAIL] {filename}: decompile error: {e}")
        continue
    
    lines = decomp_source.split('\n')
    while lines and (lines[0].startswith('#') or lines[0].strip() == ''):
        lines.pop(0)
    decomp_source = '\n'.join(lines)
    
    print(f"\n=== {filename} ===")
    print("--- Decompiled source ---")
    print(decomp_source)
    
    try:
        decomp_code = compile(decomp_source, '<decompiled>', 'exec')
    except SyntaxError as e:
        print(f"  Compile error: {e}")
        continue
    
    orig_code = load_code_from_pyc(pyc_path)
    
    # Compare top-level
    if orig_code.co_code != decomp_code.co_code:
        show_diff(orig_code, decomp_code, "module")
    
    # Compare functions
    orig_funcs = {c.co_name: c for c in orig_code.co_consts if hasattr(c, 'co_code')}
    decomp_funcs = {c.co_name: c for c in decomp_code.co_consts if hasattr(c, 'co_code')}
    for name, of in orig_funcs.items():
        if name in decomp_funcs:
            df = decomp_funcs[name]
            if of.co_code != df.co_code:
                show_diff(of, df, name)
