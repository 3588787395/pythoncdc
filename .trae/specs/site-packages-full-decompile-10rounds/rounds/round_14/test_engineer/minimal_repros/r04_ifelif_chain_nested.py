# R04 链扁平化核心形态：if/else 内嵌 if/elif/else 三臂链（结构#9 精简骨架）
def f(p, q, r):
    if p is None:
        print('new')
    else:
        q = str(q)
        if not q and not r:
            print('rec')
        elif p != q and not r:
            if r:
                print('login')
            else:
                return 'out'
        else:
            print('tail')
    return 'ret'
