# R03 三处裸 return 分布在 if/elif/else 三臂（对应原文件 550/868/1228 三处）
def f(a, b, c):
    if a is None:
        if b != 0:
            print('e1')
            return
        else:
            print('o1')
    elif not b and not c:
        if b != 0:
            print('e2')
            return
        else:
            print('o2')
    else:
        if b != 0 and c:
            print('e3')
            return
        else:
            print('o3')
    return 'ret'
