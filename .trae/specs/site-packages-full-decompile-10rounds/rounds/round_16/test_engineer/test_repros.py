# -*- coding: utf-8 -*-
"""Round 16 复现运行器。

流程：读取最小复现源码 → compile 为 orig code → core.cfg.decompile 反编译 →
re-compile → 逐函数比较 co_code / co_consts / co_exceptiontable。
结果写入 repro_results.txt（含 SUMMARY 段）。

用法：python test_repros.py   （在仓库根 F:\\Downloads\\pythoncdc-main 下执行）
"""
import io
import os
import sys
import contextlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    '..', '..', '..', '..', '..', '..'))
REPRO_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'minimal_repros')
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'repro_results.txt')

sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, '.trae', 'specs', 'site-packages-full-decompile-10rounds',
                                 'rounds', 'round_07', 'test_engineer'))
os.chdir(ROOT)

from core.cfg import decompile  # noqa: E402
from compare_bytecode import (  # noqa: E402
    collect_funcs,
    compile_decompiled_source,
    compare_func,
)


def run_one(path):
    """返回 (文件名, [ (函数名, PASS/FAIL, 明细) ... ])。"""
    with open(path, encoding='utf-8') as f:
        src = f.read()
    orig_top = compile(src, path, 'exec')
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
        dec_src = decompile(src, path)
    dec_top = compile_decompiled_source(dec_src)
    ofuncs = collect_funcs(orig_top)
    dfuncs = collect_funcs(dec_top)
    results = []
    for name in sorted(set(ofuncs) | set(dfuncs)):
        if name not in dfuncs:
            results.append((name, False, '反编译产物缺失该函数'))
            continue
        if name not in ofuncs:
            results.append((name, False, 'orig 中缺失该函数'))
            continue
        ok, detail = compare_func(ofuncs[name], dfuncs[name])
        results.append((name, ok, detail or 'match'))
    return os.path.basename(path), results


def main():
    lines = []
    files = sorted(f for f in os.listdir(REPRO_DIR) if f.endswith('.py'))
    total_pass = 0
    total_fn = 0
    file_pass = 0
    for fn in files:
        try:
            name, results = run_one(os.path.join(REPRO_DIR, fn))
        except Exception as e:
            lines.append(f'== {fn}: ERROR ({type(e).__name__}: {e})')
            continue
        ok_all = all(ok for _, ok, _ in results)
        if ok_all:
            file_pass += 1
        lines.append(f'== {name}: {"PASS" if ok_all else "FAIL"}')
        for fname, ok, detail in results:
            total_fn += 1
            if ok:
                total_pass += 1
            lines.append(f"  [{'PASS' if ok else 'FAIL'}] {fname}: {detail}")
    summary = [
        '',
        '==== SUMMARY ====',
        f'复现文件: {file_pass}/{len(files)} 全函数 PASS',
        f'函数级:   {total_pass}/{total_fn} PASS',
        '',
        '结论: FAIL 的形态构成新家族 W16「多目标链式赋值（COPY 复制栈顶供多目标）'
        '含属性/下标目标时重建缺陷」——与 W15 链式比较的 COPY 用途不同（赋值复制 vs 比较复制）：',
        '  W16-A 末目标为属性容器下标 x = <e>.attr[k] = v：输出拆为两条损坏语句，',
        '         属性限定符丢失（LOAD_ATTR argval 降级为裸全局名）、值错位为容器表达式首段；',
        '         三目标变体还蒸发中间简单名目标。',
        '  W16-B 首目标 STORE_ATTR + 末目标 STORE_SUBSCR（self.x = d[k] = v）：末目标值变 None。',
        '根因方向: region_ast_generator.py [Round8-07] 混合链处理器的 gap 校验按',
        '  「每条 LOAD_* 指令产出一个栈值」建模（STORE_SUBSCR 要求 len(gap)==2），',
        '  而 LOAD_FAST self + LOAD_ATTR _record 两条指令只产出一个值（len(gap)==3），',
        '  校验失败后落入错误回退路径，被拆成两条独立损坏赋值。',
        '控制组 R16-11（单目标下标赋值）/R16-12（纯名链与非属性容器下标链）PASS，',
        '证明触发因子是「属性访问参与赋值目标」，而非 COPY/STORE 本身。',
    ]
    lines += summary
    out = '\n'.join(lines)
    with open(OUT_PATH, 'w', encoding='utf-8') as f:
        f.write(out + '\n')
    print(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
