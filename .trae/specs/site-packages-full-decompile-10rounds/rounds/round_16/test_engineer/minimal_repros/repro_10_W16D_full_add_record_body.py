"""R16-W16D 完整 add_record 函数体上下文（record_store.pyc 同构）。

原源码语义：for + if/else + 链式赋值 else 臂 + records[-1] 更新分支。
验证控制流归约与 W16-A 缺陷叠加时整函数仍可逐函数字节码对齐。
"""
from collections import OrderedDict


class RecordStore:
    def __init__(self):
        self._record = OrderedDict()

    def add_record(self, dt, **kwargs):
        for key in kwargs:
            if key in self._record:
                records = self._record[key]
            else:
                records = self._record[key] = []
            if records and records[-1][0] == dt:
                records[-1] = (dt, kwargs[key])
            else:
                records.append((dt, kwargs[key]))
