def f(n):
    out = []
    try:
        while n > 0:
            out.append(n)
            n -= 1
    except ValueError:
        return []
    return out


def h(n):
    out = []
    try:
        while n > 0 and len(out) < 4:
            out.append(n)
            n -= 1
    except KeyError:
        out = None
    return out
