def fetch(d):
    return ({'error_no': 0}, d)


def g(flag, data):
    result = []
    error_msg, rsp_data = fetch(data)
    if error_msg['error_no'] == 0:
        stock_set = set(rsp_data.keys())
        stock_set.discard('fields')
        result += list(stock_set)
        while len(stock_set) == 3:
            error_msg, rsp_data = fetch(data)
            if error_msg['error_no'] == 0:
                stock_set = set(rsp_data.keys())
                stock_set.discard('fields')
                result += list(stock_set)
            else:
                return []
    else:
        return []
    return result
