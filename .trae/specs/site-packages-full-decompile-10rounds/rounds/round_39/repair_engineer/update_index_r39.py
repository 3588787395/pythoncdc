"""R39: update pyc_index.json after W40 repair (round 39).

按 tools/bc_cmp.py 实测结果更新三个受影响条目：
- IQEngine/api/api_base.pyc: 49/49 全匹配 → partial 转 ok
  （修复前 get_history 条件菱形未发射，R38 时 46/48→47/48）
- IQCommon/util/backtest_info_utils.pyc: 7/10=0.70（修复前 6/10=0.60）
- IQEngine/plugins/plugin_system_risk_calculation/function.pyc:
  9/15=0.60（修复前 6/15=0.40）

同时备份原索引 → pyc_index.json.bak_r39（遵循 r34-r38 惯例，
bak 文件不入库）。统一以 indent=1 重新 dump（与 HEAD 格式一致，
保持最小 diff）。

用法: D:/Python/python.exe update_index_r39.py
"""
import json
import shutil
from collections import Counter

IDX = 'F:/Downloads/pythoncdc-main/pyc_index.json'
shutil.copy(IDX, 'F:/Downloads/pythoncdc-main/pyc_index.json.bak_r39')

idx = json.load(open(IDX, encoding='utf-8'))

# path 后缀 → bc_cmp 实测 (matched, total)
targets = {
    'IQEngine/api/api_base.pyc': (49, 49),
    'IQCommon/util/backtest_info_utils.pyc': (7, 10),
    'IQEngine/plugins/plugin_system_risk_calculation/function.pyc': (9, 15),
}

changed = 0
for e in idx:
    p = e['path'].replace('\\', '/')
    for suffix, (m, t) in targets.items():
        if p.endswith(suffix):
            old_status = e.get('decompile_status')
            e['decompile_status'] = 'ok' if m == t else 'partial'
            e['bytecode_match_rate'] = round(m / t, 4)
            e['match_rate'] = round(m / t, 4)
            e['ok_py_generated'] = True
            e['last_tested_round'] = 39
            e['matched_functions'] = m
            e['total_functions'] = t
            e['mismatch_count'] = t - m
            print(f'updated: {suffix}  {old_status} -> {e["decompile_status"]}'
                  f'  {e["matched_functions"]}/{e["total_functions"]}'
                  f'  rate={e["bytecode_match_rate"]}')
            changed += 1

with open(IDX, 'w', encoding='utf-8') as f:
    json.dump(idx, f, ensure_ascii=False, indent=1)

print('updated entries:', changed)
print('status:', Counter(e['decompile_status']
                         for e in json.load(open(IDX, encoding='utf-8'))))
