#!/usr/bin/env python3
"""R39 repro harness: compile each repro source, decompile, compare bytecode per function.

参照 round_38/test_engineer/run_repros.py 结构；另覆盖 pyc 反编译路径
（compile → 写临时 .pyc → decompile_pyc），因为 W40 缺陷仅在
pyc 路径（区域识别对已有字节码分类）触发，源码路径不会复现。
两条路径均 PASS 才算 PASS。

Usage: python run_repros.py [repro_dir]
"""
import importlib.util
import marshal
import os
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = r'F:/Downloads/pythoncdc-main'
sys.path.insert(0, ROOT)

from core.cfg import decompile
from pycdc import decompile_pyc
from testqouter.round1.base import compare_bytecode


def iter_code(code, prefix=''):
    name = (prefix + '.' + code.co_name) if prefix else code.co_name
    yield name, code
    for c in code.co_consts:
        if isinstance(c, types.CodeType):
            sub = name if name != '<module>' else ''
            yield from iter_code(c, sub)


def _compare(orig, out, fails):
    compiled = compile(out, '<decomp>', 'exec')
    for name, code in iter_code(orig):
        m = None
        for n2, c2 in iter_code(compiled):
            if n2 == name:
                m = c2
                break
        if m is None:
            fails.append(f'{name}: MISSING in decompiled')
            continue
        r = compare_bytecode(code, m)
        if not r.get('match', r.get('is_match', True)):
            fails.append(f"{name}: orig={r.get('orig_count')} decomp={r.get('decomp_count')} diffs={r.get('diffs', r.get('true_diffs'))}")


def run_repro(path):
    with open(path, encoding='utf-8') as f:
        src = f.read()
    orig = compile(src, '<orig>', 'exec')

    # 路径 1：源码路径（core.cfg.decompile）
    try:
        out1 = decompile(src)
    except Exception as e:
        return False, f'DECOMPILE CRASH: {e}'
    try:
        fails = []
        _compare(orig, out1, fails)
    except SyntaxError as e:
        return False, f'SYNTAX ERROR(src path): {e}\n--- output ---\n{out1}'
    if fails:
        return False, ' | '.join(fails) + '\n--- output(src path) ---\n' + out1

    # 路径 2：pyc 反编译路径（W40 缺陷触发路径）
    pyc = os.path.join(HERE, '_tmp_repro.pyc')
    try:
        with open(pyc, 'wb') as f:
            f.write(importlib.util.MAGIC_NUMBER)
            f.write(b'\x00' * 12)
            marshal.dump(orig, f)
        out2 = decompile_pyc(pyc)
    finally:
        if os.path.exists(pyc):
            os.remove(pyc)
    try:
        fails = []
        _compare(orig, out2, fails)
    except SyntaxError as e:
        return False, f'SYNTAX ERROR(pyc path): {e}\n--- output ---\n{out2}'
    if fails:
        return False, ' | '.join(fails) + '\n--- output(pyc path) ---\n' + out2

    return True, out2


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'minimal_repros')
    files = sorted(f for f in os.listdir(d) if f.endswith('.py'))
    npass = 0
    for fn in files:
        ok, msg = run_repro(os.path.join(d, fn))
        print(f"[{'PASS' if ok else 'FAIL'}] {fn}")
        if not ok:
            for line in msg.splitlines()[:6]:
                print('    ' + line)
        else:
            npass += 1
    print(f"SUMMARY: {npass}/{len(files)} PASS")


if __name__ == '__main__':
    main()
