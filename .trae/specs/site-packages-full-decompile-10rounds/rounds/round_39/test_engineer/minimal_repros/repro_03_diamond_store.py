# W40 变体 3：菱形 if/elif/else，值块带 STORE 后接 JUMP_FORWARD
def classify(x, y):
    if x > 0:
        if y > 0:
            kind = 1
            extra = y
        elif y < 0:
            kind = 2
            extra = -y
        else:
            kind = 3
            extra = 0
    else:
        kind = 0
        extra = 0
    return kind, extra
