# 值块含赋值（对应缺陷报告中的 `if A and not include or C:` 形态）。
# 修复前：268 字节指令 -> 128（值块赋值与 else 体全部丢失）。
def get_history(asset, frequency, include, phase, obj):
    if frequency == '1d':
        sf = obj.sf
        if sf in ('1m', 'tick') and not include or phase == 1:
            query_date = obj.proxy.get_previous(obj.dt.date())
            include = False
        else:
            query_date = obj.calendar
    else:
        query_date = obj.calendar
    query_date = obj.convert(query_date)
    return {a: obj.fetch(a, query_date, include) for a in [asset]}
