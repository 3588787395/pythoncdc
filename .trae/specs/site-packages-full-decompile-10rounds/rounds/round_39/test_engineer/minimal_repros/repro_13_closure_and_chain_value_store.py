# W40 变体 E（get_history 精确复刻）：闭包 cell 变量 + BoolOp and 链条件，
# true 值块含方法调用链赋值 + 第二个 STORE_DEREF。
# 修复前：304 字节指令 -> 148（条件块整体未发射）；
# 修复后：值块含非 walrus STORE_* 时拒绝三元识别，交由 IfRegion 归约。
def get_history(asset, frequency, include, phase, obj):
    if frequency == '1d':
        sys_frequency = obj.config.strategy.frequency
        if sys_frequency in ('1m', 'tick') and include:
            if phase == 1:
                query_date = obj.proxy.get_previous(obj.dt.date())
                include = False
            else:
                query_date = obj.calendar
        else:
            query_date = obj.calendar
    else:
        query_date = obj.calendar
    query_date = obj.convert(query_date)
    return {a: obj.fetch(a, query_date, include) for a in [asset]}
