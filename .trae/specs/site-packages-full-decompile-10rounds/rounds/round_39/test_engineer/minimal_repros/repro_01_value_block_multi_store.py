# 修复前：值块 [LOAD x; STORE q; LOAD y; STORE r] 被误识别为嵌套三元链，
#         赋值语句丢失。修复后应交由 IfRegion 归约。
def get_history(freq, include, phase, dt):
    if freq == '1d':
        sys_frequency = freq
        if sys_frequency in ('1m', 'tick'):
            if include:
                if phase == 1:
                    query_date = dt
                    include = False
                else:
                    query_date = dt
            else:
                query_date = dt
        else:
            query_date = dt
    else:
        query_date = dt
    return query_date
