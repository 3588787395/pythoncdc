"""R15 probe runner: decompile probe file, compare funcs."""
import io, os, sys, contextlib
ROOT = r"F:\Downloads\pythoncdc-main"
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, '.trae', 'specs', 'site-packages-full-decompile-10rounds',
                                'rounds', 'round_07', 'test_engineer'))
os.chdir(ROOT)
from core.cfg import decompile
from compare_bytecode import collect_funcs, compile_decompiled_source, compare_func

path = sys.argv[1]
src = open(path, encoding='utf-8').read()
orig_top = compile(src, path, 'exec')
buf = io.StringIO()
with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
    dec_src = decompile(src, path)
print("--- decompiled ---")
print(dec_src)
print("--- compare ---")
dec_top = compile_decompiled_source(dec_src)
ofuncs = collect_funcs(orig_top)
dfuncs = collect_funcs(dec_top)
for name in sorted(set(ofuncs) | set(dfuncs)):
    if name not in dfuncs or name not in ofuncs:
        print(f"  [FAIL] {name}: missing")
        continue
    ok, detail = compare_func(ofuncs[name], dfuncs[name])
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {detail or 'match'}")
