import sys
sys.path.insert(0, r'F:\Downloads\pythoncdc-main')
import os
os.chdir(r'F:\Downloads\pythoncdc-main')
from core.cfg import build_cfg

src = open(sys.argv[1], encoding='utf-8').read()
fn = compile(src, sys.argv[1], 'exec').co_consts[0]
cfg = build_cfg(fn)

print("=== BLOCKS ===")
for b in cfg.get_blocks_in_order():
    instrs = ' | '.join(f"{i.offset}:{i.opname} {i.argval if i.opname not in ('CACHE',) else ''}".rstrip() for i in b.instructions)
    succs = sorted(s.start_offset for s in (b.successors or ()) if s is not None)
    preds = sorted(p.start_offset for p in (b.predecessors or ()) if p is not None)
    print(f"B[{b.start_offset}] -> {succs}  <- {preds}")
    print(f"    {instrs}")

from core.cfg.region_analyzer import RegionAnalyzer as RA
ra = RA(cfg)
regions = ra.analyze()

def bid(b):
    return b.start_offset if b is not None else None

def dump(r, depth=0):
    ind = '  ' * depth
    extra = ''
    for attr, fmt in (('condition_block','cond'), ('merge_block','merge'), ('header_block','header')):
        v = getattr(r, attr, None)
        if v is not None:
            extra += f' {fmt}={bid(v)}'
    cc = getattr(r, 'chained_compare_ops', None)
    if cc:
        extra += f' cc_ops={cc!r}'
    ccb = getattr(r, 'chained_compare_blocks', None)
    if ccb:
        extra += f' cc_blocks={[bid(x) for x in ccb]}'
    for attr, fmt in (('then_blocks','then'), ('else_blocks','else'), ('body_blocks','body')):
        v = getattr(r, attr, None)
        if v:
            try:
                extra += f' {fmt}={sorted(bid(x) for x in v)}'
            except TypeError:
                extra += f' {fmt}={v}'
    print(f'{ind}{type(r).__name__} entry={bid(r.entry)} blocks={sorted(bid(x) for x in r.blocks)}{extra}')
    for c in (getattr(r, 'children', None) or []):
        dump(c, depth+1)

print("=== REGIONS ===")
for r in regions:
    dump(r)
