LOG = []
def wrap(cls, name):
    orig = getattr(cls, name)
    def patched(self, *a, **k):
        ret = orig(self, *a, **k)
        cb = a[0] if a else k.get('cond_block')
        soff = getattr(cb, 'start_offset', None)
        LOG.append(f"  {name} cond_block={soff} -> {'None' if ret is None else type(ret).__name__}")
        if name == '_extract_vc_pre_store_statements':
            import dis as dm
            instrs = list(getattr(cb, 'instructions', []) or [])
            LOG.append(f"      instrs={[i.opname for i in instrs]}")
            LOG.append(f"      ret={ret!r:.400}")
        return ret
    setattr(cls, name, patched)

for nm in ('_extract_vc_pre_store_statements',):
    if hasattr(RegionASTGenerator, nm):
        wrap(RegionASTGenerator, nm)

_orig_bsf = RegionASTGenerator._build_statements_from_instructions
def _bsf_patched(self, instrs, block=None):
    ret = _orig_bsf(self, instrs, block)
    LOG.append(f"  _build_statements_from_instructions n={len(instrs)} first={[i.opname for i in instrs[:3]]} -> {ret!r:.300}")
    return ret
RegionASTGenerator._build_statements_from_instructions = _bsf_patched

