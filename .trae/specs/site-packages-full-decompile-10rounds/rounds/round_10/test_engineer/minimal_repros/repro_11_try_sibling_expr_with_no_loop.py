"""R10-W10 最小复现 11（形态 B）：TryRegion 兄弟位表达式语句被吞——无需循环。

try/except 与 try/finally 之后的兄弟位上、with 前的表达式语句均被吞；
赋值语句 w = wrap(v) 幸存。预期：修复前 FAIL；修复后 PASS。
"""


def after_except(mapping):
    try:
        v = mapping['k']
    except KeyError:
        v = None
    w = wrap(v)
    use(v)
    with open('x') as fh:
        fh.write(v)
    return w


def after_finally(mapping):
    try:
        v = mapping['k']
    finally:
        cleanup()
    note(v)
    with open('x') as fh:
        fh.write(v)
