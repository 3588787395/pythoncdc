def generate_report(result_dict, target_dir):
    xlsx_writer = make_writer(target_dir)
    df = build(result_dict)
    df.to_excel(xlsx_writer, sheet_name='summary')
    with open('summary.csv', 'w') as csvfile:
        csvfile.write(df.text())
    for name in ('a', 'b'):
        try:
            df = result_dict[name]
        except KeyError:
            log_missing()
            continue
        if df.index_name() == 'date':
            df = df.reset()
            df = df.set('date')
        csv_txt = new_buffer()
        csv_txt.write(df.to_csv(encoding='utf-8'))
        df.to_excel(xlsx_writer, sheet_name=name)
        with open('{}.csv'.format(name), 'w') as csvfile:
            csvfile.write(csv_txt.getvalue())
    xlsx_writer.save()
