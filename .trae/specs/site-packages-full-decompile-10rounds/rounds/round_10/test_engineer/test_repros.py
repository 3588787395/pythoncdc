# -*- coding: utf-8 -*-
"""Round 10 最小复现实例运行器。

流程（每个 repro）：
  1. 读取 repro 源码，compile() 得原始 code object（基线）
  2. core.cfg.decompile(src) 反编译
  3. 剥离 # 头部行后 re-compile()
  4. 递归收集函数，逐函数 co_code 字节级比较（复用 round_07 compare_bytecode 工具）

结果写入 repro_results.txt 并打印 SUMMARY。
W10 缺陷家族（双触发面）：
  形态 A：循环体内 with 前同一线性段的兄弟表达式语句被吞（repro_01～10、06）；
  形态 B：TryRegion(except/finally) 兄弟位上 with 前表达式语句被吞，无需循环（repro_11）。
修复目标：repro_01～11 全 PASS；repro_12/13 为对照组应保持 PASS。
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = r'F:\Downloads\pythoncdc-main'
R07 = os.path.join(PROJ, '.trae', 'specs', 'site-packages-full-decompile-10rounds',
                   'rounds', 'round_07', 'test_engineer')
sys.path.insert(0, PROJ)
sys.path.insert(0, R07)

from compare_bytecode import compile_decompiled_source, collect_funcs, first_code_diff  # noqa: E402
from core.cfg import decompile  # noqa: E402

REPRO_DIR = os.path.join(HERE, 'minimal_repros')
RESULT_FILE = os.path.join(HERE, 'repro_results.txt')


def compare_co_code(orig_top, decomp_top):
    """逐函数 co_code 字节级比较，返回 (passed, total, [(名称, ok, 明细)])。"""
    ofuncs = collect_funcs(orig_top)
    dfuncs = collect_funcs(decomp_top)
    results = []
    passed = 0
    for name in sorted(set(ofuncs) | set(dfuncs)):
        if name not in dfuncs:
            results.append((name, False, '反编译产物中缺失该函数'))
            continue
        if name not in ofuncs:
            results.append((name, False, '原源码中缺失该函数'))
            continue
        o, d = ofuncs[name], dfuncs[name]
        if o.co_code == d.co_code:
            passed += 1
            results.append((name, True, 'match'))
        else:
            results.append((name, False,
                            f'co_code 不一致 ({len(o.co_code)} vs {len(d.co_code)} 字节): '
                            f'{first_code_diff(o, d)}'))
    return passed, len(results), results


def run_repro(path):
    """单个 repro：compile → decompile → re-compile → 比较。返回 (ok, 输出行列表)。"""
    name = os.path.basename(path)
    lines = [f'=== {name} ===']
    with open(path, encoding='utf-8') as f:
        src = f.read()
    try:
        orig = compile(src, name, 'exec')
    except SyntaxError as e:
        lines.append(f'  [ERROR] 原 source 无法编译: {e}')
        return False, lines
    try:
        dec = decompile(src)
    except Exception as e:
        lines.append(f'  [ERROR] decompile 异常: {type(e).__name__}: {e}')
        return False, lines
    try:
        new = compile_decompiled_source(dec)
    except SyntaxError as e:
        snippet = '\n'.join(dec.split('\n')[:40])
        lines.append(f'  [ERROR] 反编译产物无法编译: {e}')
        lines.append('  --- 反编译输出前 40 行 ---')
        for ln in snippet.split('\n'):
            lines.append(f'  | {ln}')
        return False, lines
    passed, total, details = compare_co_code(orig, new)
    for fname, ok, detail in details:
        tag = 'PASS' if ok else 'FAIL'
        lines.append(f'  [{tag}] {fname}: {detail}')
    ok = (passed == total and total > 0)
    lines.append(f'  == {passed}/{total} {"ALL PASS" if ok else "HAS FAIL"}')
    return ok, lines


def main():
    repros = sorted(f for f in os.listdir(REPRO_DIR) if f.endswith('.py'))
    out_lines = ['Round 10 W10 基线结果（with 前兄弟表达式语句被吞，双触发面：循环体内 / TryRegion 兄弟位；FAIL 集为修复目标基线）',
                 '=' * 60]
    n_pass = 0
    n_file_pass = 0
    total_funcs = 0
    passed_funcs = 0
    for rp in repros:
        path = os.path.join(REPRO_DIR, rp)
        ok, lines = run_repro(path)
        n_file_pass += ok
        for ln in lines:
            out_lines.append(ln)
            if ln.strip().startswith('[PASS]'):
                passed_funcs += 1
                total_funcs += 1
            elif ln.strip().startswith('[FAIL]'):
                total_funcs += 1
        out_lines.append('')
    summary = [
        '=' * 60,
        f'SUMMARY: files {n_file_pass}/{len(repros)} all-pass, '
        f'functions {passed_funcs}/{total_funcs} PASS',
        f'基线结论: 当前 FAIL 集（{total_funcs - passed_funcs} 函数）即 R10/W10 修复目标基线；',
        f'repro_12/repro_13 为对照组（with 后置与唯一语句 / 吞噬边界对照，应保持 PASS）。',
    ]
    out_lines.extend(summary)
    text = '\n'.join(out_lines)
    with open(RESULT_FILE, 'w', encoding='utf-8') as f:
        f.write(text + '\n')
    print(text)


if __name__ == '__main__':
    main()
